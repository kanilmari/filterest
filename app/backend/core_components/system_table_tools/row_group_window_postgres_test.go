// row_group_window_postgres_test.go
// Proves class replacement, idempotence, legacy stable keys and competing writes.
// Bridges exact released migrations with two independent disposable PostgreSQL connections.
// Exists to test lock snapshots and persistence that a mock database cannot establish.
package system_table_tools

