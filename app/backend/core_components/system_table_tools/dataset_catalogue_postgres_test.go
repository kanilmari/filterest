func catalogueRequest(t *testing.T, userID int) *http.Request {
	t.Helper()
	request := httptest.NewRequest("GET", "/api/datasets", nil)
	session, err := esessions.Store.Get(request, esessions.SessionName)
	if err != nil {
		t.Fatal(err)
	}
	session.Values["user_id"] = userID
	cookie := httptest.NewRecorder()
	if err := session.Save(request, cookie); err != nil {
		t.Fatal(err)
	}
	request = httptest.NewRequest("GET", "/api/datasets", nil)
	for _, c := range cookie.Result().Cookies() {
		request.AddCookie(c)
	}
	return request
}

func catalogueDisposableDatabase(t *testing.T) *sql.DB {
	t.Helper()
	db := sitePresentationDisposableDB(t)
	if _, err := db.Exec(datasetCatalogueFixture); err != nil {
		t.Fatal(err)
	}
	previous := backend.Db
	backend.Db = db
	backend.ResetEaselectInstanceRoleCache()
	oldStore, oldName := esessions.Store, esessions.SessionName
	esessions.Store, esessions.SessionName = sessions.NewCookieStore([]byte("wl159-catalogue-test-cookie-key32")), "wl159-test"
	t.Cleanup(func() {
		backend.Db = previous
		backend.ResetEaselectInstanceRoleCache()
		esessions.Store, esessions.SessionName = oldStore, oldName
	})

	return db
}

func TestDatasetCataloguePostgresGuestsReadersAdminsAndEmpty(t *testing.T) {
	db := catalogueDisposableDatabase(t)
	t.Setenv("FILTEREST_ADMIN_PERMISSION_RECOVERY_MODE", "0")

	for _, fixture := range []struct {
		user  int
		names []string
		uids  map[int]bool
	}{
		{1, []string{"app_automatic", "app_orders"}, map[int]bool{11: true, 15: true}},
		{42, []string{"app_automatic", "app_orders"}, map[int]bool{11: true, 15: true}},
		{99, []string{"app_automatic", "app_hidden", "app_orders", "app_private", "automatic"}, map[int]bool{11: true, 13: true, 14: true, 15: true, 16: true}},
		{73, []string{}, map[int]bool{}},
	} {
		t.Run(fmt.Sprintf("user_%d", fixture.user), func(t *testing.T) {
			readable, err := access_control.GetTablesReadableByUser(db, fixture.user)
			if err != nil || !reflect.DeepEqual(readable, fixture.uids) {
				t.Fatalf("read set=%v err=%v", readable, err)
			}
			response := httptest.NewRecorder()
			GetGroupedTables(response, catalogueRequest(t, fixture.user))
			var body struct {
				Datasets []dtt_models.Table       `json:"datasets"`
				TabOrder []catalogueTabOrderEntry `json:"tab_order"`
			}
			if err := json.Unmarshal(response.Body.Bytes(), &body); err != nil {
				t.Fatal(err)
			}
			if response.Code != 200 || response.Header().Get("Cache-Control") != "private, no-store" {
				t.Fatalf("response %d %s", response.Code, response.Body.String())
			}
			expectedOrder := []catalogueTabOrderEntry{{"app_orders", 0}, {"static:login", 1}, {"app_automatic", 2}}
			if fixture.user == 99 {
				expectedOrder = []catalogueTabOrderEntry{{"app_private", 0}, {"app_orders", 1}, {"static:login", 2}, {"app_automatic", 3}}
			}
			if fixture.user == 73 {
				expectedOrder = []catalogueTabOrderEntry{{"static:login", 0}}
			}
			if !reflect.DeepEqual(body.TabOrder, expectedOrder) {
				t.Fatalf("saved order leaked: %v want %v", body.TabOrder, expectedOrder)
			}
			gotNames := make([]string, 0)
			for _, entry := range body.Datasets {
				gotNames = append(gotNames, entry.TableName)
				for _, name := range entry.Names {
					if raw := dataset_routes.ResolveRawDatasetNameWithQuerier(db, name); raw != entry.TableName {
						t.Fatalf("published name %s resolves as %s", name, raw)
					}
				}
				if entry.ID == entry.TableUID || !entry.CanReadRows {
					t.Fatalf("wrong identity/read flag: %+v", entry)
				}
				if entry.TableName == "app_orders" && (!reflect.DeepEqual(entry.Names, []string{"app_orders", "old-orders", "shop-orders"}) || entry.PreferredName != "shop-orders") {
					t.Fatalf("pool: %+v", entry)
				}
				// A hidden real name reserves the automatic alias for all viewers.
				if entry.TableName == "app_automatic" && !reflect.DeepEqual(entry.Names, []string{"app_automatic"}) {
					t.Fatalf("hidden owner leaked into pool: %+v", entry)
				}
			}
			if body.Datasets == nil || !reflect.DeepEqual(gotNames, fixture.names) {
				t.Fatalf("names=%v, want %v; %s", gotNames, fixture.names, response.Body.String())
			}
			if fixture.user != 99 && (strings.Contains(response.Body.String(), "hidden-orders") || strings.Contains(response.Body.String(), "private-orders")) {
				t.Fatal("unreadable aliases leaked")
			}
		})
	}
}

func TestDatasetCataloguePostgresAdministratorRecoveryMatchesRowReads(t *testing.T) {
	db := catalogueDisposableDatabase(t)
	for _, fixture := range []struct {
		environment, recovery string
		user                  int
		readable              bool
	}{
		{"dev", "0", 99, false}, {"dev", "1", 99, true}, {"dev", "1", 42, false}, {"production", "1", 99, false},
	} {
		t.Setenv("ENVIRONMENT_TYPE", fixture.environment)
		t.Setenv("FILTEREST_ADMIN_PERMISSION_RECOVERY_MODE", fixture.recovery)
		rowsAllowed := access_control.UserHasFunctionPermissionOnTableQuiet(fixture.user, "/api/get-results", "app_write_only", "12")
		catalogue, err := access_control.GetTablesReadableByUser(db, fixture.user)
		if err != nil || rowsAllowed != fixture.readable || catalogue[12] != rowsAllowed {
			t.Fatalf("%+v rows=%v catalogue=%v error=%v", fixture, rowsAllowed, catalogue, err)
		}
		response := httptest.NewRecorder()
		GetGroupedTables(response, catalogueRequest(t, fixture.user))
		if response.Code != 200 || strings.Contains(response.Body.String(), "app_write_only") != rowsAllowed {
			t.Fatalf("catalogue HTTP disagrees with rows: %s", response.Body.String())
		}
	}
}

func TestDatasetCataloguePostgresRuntimeRegistrationGrantsAdmins(t *testing.T) {
	db := catalogueDisposableDatabase(t)
	t.Setenv("FILTEREST_ADMIN_PERMISSION_RECOVERY_MODE", "0")
	if _, err := db.Exec("CREATE TABLE app_runtime_orders (id integer PRIMARY KEY, title text)"); err != nil {
		t.Fatal(err)
	}
	tx, err := db.Begin()
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	if err := fixIssue(tx, "cat2_app_runtime_orders", map[string]string{"cat2_app_runtime_orders": "register"}); err != nil {
		t.Fatal(err)
	}
	var uid, grantCount int
	if err := tx.QueryRow("SELECT table_uid FROM system_db_tables WHERE table_name='app_runtime_orders'").Scan(&uid); err != nil {
		t.Fatal(err)
	}
	if err := tx.QueryRow("SELECT count(*) FROM system_group_table_func_rights WHERE user_group_id=1 AND target_table_uid=$1 AND target_schema_name='public'", uid).Scan(&grantCount); err != nil {
		t.Fatal(err)
	}
	if grantCount != 2 {
		t.Fatalf("registered dataset received %d admin grants, want both enabled dataset functions", grantCount)
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	for _, user := range []int{1, 42, 99} {
		rowsAllowed := access_control.UserHasFunctionPermissionOnTableQuiet(user, "/api/get-results", "app_runtime_orders", fmt.Sprint(uid))
		catalogue, err := access_control.GetTablesReadableByUser(db, user)
		if err != nil || catalogue[uid] != (user == 99) || rowsAllowed != catalogue[uid] {
			t.Fatalf("user %d catalogue=%v rows=%v error=%v", user, catalogue, rowsAllowed, err)
		}
		response := httptest.NewRecorder()
		GetGroupedTables(response, catalogueRequest(t, user))
		if response.Code != 200 || strings.Contains(response.Body.String(), "app_runtime_orders") != (user == 99) {
			t.Fatalf("runtime catalogue mismatch: %s", response.Body.String())
		}
	}
}

