// keySnapshot is one key's complete state in both stores and its sources, as comparable JSON text.
func keySnapshot(t *testing.T, db *sql.DB, langKey string) (columns, rows, sources string) {
	t.Helper()
	if err := db.QueryRow(`
		SELECT to_jsonb(k) - 'id' - 'created' - 'updated',
		       COALESCE((SELECT jsonb_agg(to_jsonb(r) - 'id' - 'lang_key_id' ORDER BY r.language_code)
		                 FROM system_lang_key_translations r WHERE r.lang_key_id = k.id), '[]'),
		       COALESCE((SELECT jsonb_agg(to_jsonb(s) - 'id' - 'lang_key_id' - 'last_seen' ORDER BY s.source_type, s.source_high)
		                 FROM system_lang_key_sources s WHERE s.lang_key_id = k.id), '[]')
		FROM system_lang_keys k WHERE k.lang_key = $1`, langKey).Scan(&columns, &rows, &sources); err != nil {
		t.Fatalf("snapshot %s: %v", langKey, err)
	}
	return columns, rows, sources
}

func runLabelRenameWithOutcome(t *testing.T, db *sql.DB, rename ItemLabelRename) (ItemLabelOutcome, error) {
	t.Helper()
	tx, err := db.Begin()
	if err != nil {
		t.Fatal(err)
	}
	outcome, err := MoveRenamedItemLabel(tx, rename)
	if err != nil {
		_ = tx.Rollback()
		return outcome, err
	}
	return outcome, tx.Commit()
}

func runLabelRename(t *testing.T, db *sql.DB, rename ItemLabelRename) error {
	t.Helper()
	_, err := runLabelRenameWithOutcome(t, db, rename)
	return err
}

func scalarText(t *testing.T, db *sql.DB, query string, args ...interface{}) string {
	t.Helper()
	var value sql.NullString
	if err := db.QueryRow(query, args...).Scan(&value); err != nil {
		t.Fatalf("%s: %v", query, err)
	}
	return value.String
}

func TestItemLabelRenameKeepsTheSharedKeyAndEveryLanguagePostgres(t *testing.T) {
	var notices []string
	db := translationDisposableDB(t, &notices)
	if _, err := db.Exec(itemLabelPostgresFixture); err != nil {
		t.Fatal(err)
	}
	oldColumns, oldRows, _ := keySnapshot(t, db, "app_orders")

	// The dialog showed fi and en; the administrator changed only the English text.
	if err := runLabelRename(t, db, ItemLabelRename{SourceType: "table", OldKey: "app_orders", NewKey: "app_sales_orders",
		Translations: map[string]string{"fi": "Tilaukset", "en": "Sales orders"},
		Shown:        map[string]string{"fi": "Tilaukset", "en": "Orders"}}); err != nil {
		t.Fatal(err)
	}

	columns, rows, sources := keySnapshot(t, db, "app_orders")
	if columns != oldColumns || rows != oldRows {
		t.Fatalf("the shared old key changed:\n%s\n%s", columns, rows)
	}
	if want := `[{"source_low": "", "source_high": "frontend/orders_widget.js", "source_type": "code", "usage_explanation": "Orders widget heading"}, {"source_low": "app_orders", "source_high": "app_invoices", "source_type": "column", "usage_explanation": "Column 'app_orders' in table 'app_invoices'"}]`; sources != want {
		t.Fatalf("old key sources: only the dataset's own source may move:\n%s", sources)
	}

	columns, rows, sources = keySnapshot(t, db, "app_sales_orders")
	if want := `{"ch": "订单", "en": "Sales orders", "fi": "Tilaukset", "yue": "訂單", "lang_key": "app_sales_orders", "creation_spec": "Interface label derived from dataset schema names.", "lang_key_type": 2}`; columns != want {
		t.Fatalf("new key columns:\n%s", columns)
	}
	for _, check := range []struct{ code, text, kind, review string }{
		{"fi", "Tilaukset", "legacy_fi", "approved"},
		{"en", "Sales orders", "manual", "approved"},
		{"zh-CN", "订单", "legacy_ch", "needs_review"},
		{"zh-TW", "訂單（台）", "import", "unreviewed"},
		{"zh-HK", "訂單", "manual", "needs_review"},
		{"sv", "Beställningar", "manual", "approved"},
	} {
		var text, kind, review string
		if err := db.QueryRow(`SELECT r.translation, r.source_kind, r.review_status FROM system_lang_key_translations r
			JOIN system_lang_keys k ON k.id = r.lang_key_id WHERE k.lang_key = 'app_sales_orders' AND r.language_code = $1`,
			check.code).Scan(&text, &kind, &review); err != nil || text != check.text || kind != check.kind || review != check.review {
			t.Fatalf("language %s on the new key: %q %q %q %v\n%s", check.code, text, kind, review, err, rows)
		}
	}
	if want := `[{"source_low": "app_sales_orders", "source_high": "app_sales_orders", "source_type": "table", "usage_explanation": "Table 'app_orders'"}]`; sources != want {
		t.Fatalf("new key sources:\n%s", sources)
	}
}

// Owner, 22.11.2026: "Älä muuta jaettua avainta". The new name's key already exists and is shared.
func TestItemLabelRenameOntoAnExistingKeyKeepsItsTextsAndReportsThemPostgres(t *testing.T) {
	var notices []string
	db := translationDisposableDB(t, &notices)
	if _, err := db.Exec(itemLabelPostgresFixture); err != nil {
		t.Fatal(err)
	}
	oldColumns, oldRows, _ := keySnapshot(t, db, "app_orders")

	// The administrator typed new English and kept the Finnish prefill of the old key.
	outcome, err := runLabelRenameWithOutcome(t, db, ItemLabelRename{SourceType: "folder", OldKey: "app_orders", NewKey: "purchase_orders",
		Translations: map[string]string{"fi": "Tilaukset", "en": "Customer orders"},
		Shown:        map[string]string{"fi": "Tilaukset", "en": "Orders"}})
	if err != nil {
		t.Fatal(err)
	}
	// Finnish shows "Ostotilaukset" through the existing key's row and English "Purchase orders":
	// both differ from the dialog, so the person is told the name uses the existing texts.
	if outcome.LangKey != "purchase_orders" || !reflect.DeepEqual(outcome.KeptLanguages, []string{"fi", "en"}) {
		t.Fatal("notice", outcome)
	}
	// The shared texts are unchanged; only Chinese, which it showed in neither store, is filled
	// from the old key. Cantonese stays empty because Traditional Chinese already shows it.
	if got := scalarText(t, db, `SELECT to_jsonb(k) - 'id' - 'created' - 'updated' FROM system_lang_keys k WHERE lang_key = 'purchase_orders'`); got != `{"ch": "订单", "en": "Purchase orders", "fi": "", "yue": null, "lang_key": "purchase_orders", "creation_spec": "Interface label derived from dataset schema names.", "lang_key_type": 2}` {
		t.Fatalf("existing key columns:\n%s", got)
	}
	if got := scalarText(t, db, `SELECT string_agg(r.language_code || '=' || r.translation || '/' || r.source_kind || '/' || r.review_status, ', ' ORDER BY r.language_code)
		FROM system_lang_key_translations r JOIN system_lang_keys k ON k.id = r.lang_key_id WHERE k.lang_key = 'purchase_orders'`); got != "en=Purchase orders/manual/approved, fi=Ostotilaukset/manual/approved, sv=Beställningar/manual/approved, zh-CN=订单/legacy_ch/needs_review, zh-TW=採購訂單/manual/approved" {
		t.Fatalf("existing key rows:\n%s", got)
	}
	if columns, rows, _ := keySnapshot(t, db, "app_orders"); columns != oldColumns || rows != oldRows {
		t.Fatal("the old key changed")
	}
	if got := sourceListOf(t, db, "purchase_orders"); got != "code:frontend/purchasing.js, folder:purchase_orders" {
		t.Fatal("sources:", got)
	}

	// Blank fields and text that matches the key need no notice.
	outcome, err = runLabelRenameWithOutcome(t, db, ItemLabelRename{SourceType: "folder", OldKey: "purchase_orders", NewKey: "purchase_orders",
		Translations: map[string]string{"fi": "", "en": "Purchase orders"}})
	if err != nil || len(outcome.KeptLanguages) != 0 {
		t.Fatal(outcome, err)
	}
}

func sourceListOf(t *testing.T, db *sql.DB, langKey string) string {
	t.Helper()
	return scalarText(t, db, `SELECT string_agg(s.source_type || ':' || s.source_high, ', ' ORDER BY s.source_type, s.source_high)
		FROM system_lang_key_sources s JOIN system_lang_keys k ON k.id = s.lang_key_id WHERE k.lang_key = $1`, langKey)
}

func TestItemLabelRenameSameNameEditsOnlyTheTypedLanguagePostgres(t *testing.T) {
	var notices []string
	db := translationDisposableDB(t, &notices)
	if _, err := db.Exec(itemLabelPostgresFixture); err != nil {
		t.Fatal(err)
	}
	if err := runLabelRename(t, db, ItemLabelRename{SourceType: "table", OldKey: "app_orders", NewKey: "app_orders",
		Translations: map[string]string{"fi": "Tilauskanta", "en": "", "ch": " "},
		Shown:        map[string]string{"fi": "Tilaukset", "en": "Orders"}}); err != nil {
		t.Fatal(err)
	}
	if got := scalarText(t, db, `SELECT to_jsonb(k) - 'id' - 'created' - 'updated' - 'creation_spec' - 'lang_key_type' FROM system_lang_keys k WHERE lang_key = 'app_orders'`); got != `{"ch": "订单", "en": "Orders", "fi": "Tilauskanta", "yue": "訂單", "lang_key": "app_orders"}` {
		t.Fatalf("columns:\n%s", got)
	}
	if got := scalarText(t, db, `SELECT string_agg(r.language_code || '=' || r.translation || '/' || r.source_kind, ', ' ORDER BY r.language_code)
		FROM system_lang_key_translations r JOIN system_lang_keys k ON k.id = r.lang_key_id WHERE k.lang_key = 'app_orders'`); got != "en=Orders/legacy_en, fi=Tilauskanta/manual, sv=Beställningar/manual, zh-CN=订单/legacy_ch, zh-HK=訂單/manual, zh-TW=訂單（台）/import" {
		t.Fatalf("rows:\n%s", got)
	}

	// A dialog opened before that edit is refused instead of overwriting it.
	err := runLabelRename(t, db, ItemLabelRename{SourceType: "table", OldKey: "app_orders", NewKey: "app_orders",
		Translations: map[string]string{"fi": "Tilausrekisteri"}, Shown: map[string]string{"fi": "Tilaukset"}})
	if !errors.Is(err, ErrItemLabelConflict) {
		t.Fatal("stale dialog accepted", err)
	}

	// The dialog reads only the legacy column. A Finnish text another administrator kept in the
	// normalized row alone was never shown, so typed Finnish must not replace it.
	if _, err := db.Exec(`UPDATE system_lang_keys SET fi = '' WHERE lang_key = 'app_orders';
		UPDATE system_lang_key_translations SET translation = 'Tilausrekisteri (uusi)'
		WHERE language_code = 'fi' AND lang_key_id = (SELECT id FROM system_lang_keys WHERE lang_key = 'app_orders')`); err != nil {
		t.Fatal(err)
	}
	columns, rows, _ := keySnapshot(t, db, "app_orders")
	err = runLabelRename(t, db, ItemLabelRename{SourceType: "table", OldKey: "app_orders", NewKey: "app_orders",
		Translations: map[string]string{"fi": "Tilauslista", "en": "Orders"}, Shown: map[string]string{"fi": "", "en": "Orders"}})
	if !errors.Is(err, ErrItemLabelConflict) {
		t.Fatal("normalized-only text overwritten", err)
	}
	if afterColumns, afterRows, _ := keySnapshot(t, db, "app_orders"); afterColumns != columns || afterRows != rows {
		t.Fatal("a refused rename changed the key")
	}
}

func TestItemLabelRenameCreatesALabelForAnUnlabelledItemPostgres(t *testing.T) {
	var notices []string
	db := translationDisposableDB(t, &notices)
	if _, err := db.Exec(itemLabelPostgresFixture); err != nil {
		t.Fatal(err)
	}
	if err := runLabelRename(t, db, ItemLabelRename{SourceType: "folder", OldKey: "unlabelled_folder", NewKey: "archive_folder",
		Translations: map[string]string{"fi": "Arkisto", "en": "Archive"}}); err != nil {
		t.Fatal(err)
	}
	_, rows, sources := keySnapshot(t, db, "archive_folder")
	if got := scalarText(t, db, `SELECT fi || '/' || en FROM system_lang_keys WHERE lang_key = 'archive_folder'`); got != "Arkisto/Archive" {
		t.Fatal(got, rows)
	}
	if want := `[{"source_low": "archive_folder", "source_high": "archive_folder", "source_type": "folder", "usage_explanation": ""}]`; sources != want {
		t.Fatal(sources)
	}
}
