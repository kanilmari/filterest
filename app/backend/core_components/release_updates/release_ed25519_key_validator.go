// release_ed25519_key_validator.go
// Rejects small-order Ed25519 public-key encodings before they can establish trust.
// Connects operator policy validation and encrypted key metadata to signature checks.
// Blocks constant-signature forgeries, including non-canonical field encodings.
package release_updates

import "bytes"

// libsodium's Ed25519 ge25519_has_small_order list includes y=0, 1, two
// order-eight Edwards coordinates (not the X25519 Montgomery blocklist),
// -1, p and p+1. Masking the sign bit covers both encodings of each coordinate.
// p and p+1 are the non-canonical encodings of 0 and 1 in the 255-bit field.
var smallOrderEd25519Encodings = [7][32]byte{
	{},
	{1},
	{0x26, 0xe8, 0x95, 0x8f, 0xc2, 0xb2, 0x27, 0xb0, 0x45, 0xc3, 0xf4, 0x89, 0xf2, 0xef, 0x98, 0xf0, 0xd5, 0xdf, 0xac, 0x05, 0xd3, 0xc6, 0x33, 0x39, 0xb1, 0x38, 0x02, 0x88, 0x6d, 0x53, 0xfc, 0x05},
	{0xc7, 0x17, 0x6a, 0x70, 0x3d, 0x4d, 0xd8, 0x4f, 0xba, 0x3c, 0x0b, 0x76, 0x0d, 0x10, 0x67, 0x0f, 0x2a, 0x20, 0x53, 0xfa, 0x2c, 0x39, 0xcc, 0xc6, 0x4e, 0xc7, 0xfd, 0x77, 0x92, 0xac, 0x03, 0x7a},
	{0xec, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
	{0xed, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
	{0xee, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0x7f},
}

func smallOrderEd25519PublicKey(public []byte) bool {
	if len(public) != 32 {
		return true
	}
	var coordinate [32]byte
	copy(coordinate[:], public)
	coordinate[31] &= 0x7f
	for _, blocked := range smallOrderEd25519Encodings {
		if bytes.Equal(coordinate[:], blocked[:]) {
			return true
		}
	}
	return false
}
