// dataset_namespace_postgres_test.go
// Proves audit preservation and concurrent namespace ownership in real PostgreSQL.
// Uses an explicitly enabled disposable local cluster, never installation credentials.
// Removing the DB lock makes the concurrency tests fail before either writer commits.
