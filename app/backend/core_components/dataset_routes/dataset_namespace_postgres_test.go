const namespaceMigration = "20261009000078_enforce_dataset_name_namespace.sql"

func namespacePostgres(t *testing.T, legacy bool) *sql.DB {
	t.Helper()
	if os.Getenv("FILTEREST_TEST_DISPOSABLE_POSTGRES") != "1" {
		t.Skip("set FILTEREST_TEST_DISPOSABLE_POSTGRES=1 for disposable namespace verification")
	}
	root, err := os.MkdirTemp("", "filterest-ns-")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { os.RemoveAll(root) })
	socket, data := filepath.Join(root, "socket"), filepath.Join(root, "db")
	if err := os.Mkdir(socket, 0700); err != nil {
		t.Fatal(err)
	}
	bin := "/usr/lib/postgresql/16/bin/"
	run := func(name string, args ...string) {
		t.Helper()
		if output, err := exec.Command(bin+name, args...).CombinedOutput(); err != nil {
			t.Fatalf("%s: %v: %s", name, err, output)
		}
	}
	run("initdb", "-D", data, "-A", "trust", "-U", "namespace_owner", "--no-locale", "--encoding=UTF8")
	run("pg_ctl", "-D", data, "-l", filepath.Join(root, "postgres.log"), "-o", "-h '' -k '"+socket+"' -p 15479", "-w", "start")
	t.Cleanup(func() { run("pg_ctl", "-D", data, "-m", "immediate", "-w", "stop") })
	db, err := sql.Open("postgres", "host="+socket+" port=15479 user=namespace_owner dbname=postgres sslmode=disable")
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { db.Close() })
	namespaceExec(t, db, `CREATE TABLE public.system_db_tables (
        id serial PRIMARY KEY, table_uid integer NOT NULL UNIQUE, table_name text, schema_name text DEFAULT 'public');
        CREATE TABLE public.system_data_repair_records (migration text, action text, detail jsonb);
        CREATE TABLE public.system_lang_keys (id serial PRIMARY KEY, lang_key text UNIQUE,fi text,en text,ch text,yue text,creation_spec text);
        CREATE TABLE public.system_languages(language_code text PRIMARY KEY);
        INSERT INTO public.system_languages VALUES ('fi'),('en'),('ch'),('yue');
        CREATE TABLE public.system_lang_key_translations(lang_key_id integer,language_code text,translation text,source_kind text,review_status text,PRIMARY KEY(lang_key_id,language_code));
        CREATE TABLE public."Reports"(id integer);
        CREATE TABLE public.system_alpha(id integer);
        CREATE TABLE public.system_beta(id integer);
        INSERT INTO public.system_db_tables(id,table_uid,table_name) VALUES (901,11,'Reports'),(902,12,'system_alpha'),(903,13,'system_beta');`)
	timestamp, slug, primary := "timestamptz", "text", "false"
	if legacy {
		timestamp, slug, primary = "timestamp without time zone", "varchar(128)", "true"
	}
	namespaceExec(t, db, fmt.Sprintf(`CREATE TABLE public.system_db_table_aliases (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        table_uid integer NOT NULL REFERENCES public.system_db_tables(table_uid) ON DELETE CASCADE,
        alias_slug %s NOT NULL, is_primary boolean NOT NULL DEFAULT %s, is_active boolean NOT NULL DEFAULT true,
        created %s NOT NULL DEFAULT now(), updated %s NOT NULL DEFAULT now());`, slug, primary, timestamp, timestamp))
	if legacy {
		namespaceExec(t, db, `CREATE UNIQUE INDEX system_db_table_aliases_alias_slug_key ON public.system_db_table_aliases(alias_slug);
        CREATE UNIQUE INDEX system_db_table_aliases_one_primary_per_table_key ON public.system_db_table_aliases(table_uid) WHERE is_primary IS TRUE;`)
	} else {
		namespaceExec(t, db, `ALTER TABLE public.system_db_table_aliases ADD CONSTRAINT system_db_table_aliases_alias_slug_key UNIQUE(alias_slug);
        CREATE UNIQUE INDEX idx_system_db_table_aliases_one_primary_alias_per_table ON public.system_db_table_aliases(table_uid) WHERE is_primary IS TRUE AND is_active IS TRUE;
        CREATE FUNCTION public.set_system_db_table_aliases_updated_timestamp() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN NEW.updated=now(); RETURN NEW; END; $$;
        CREATE TRIGGER set_system_db_table_aliases_updated BEFORE UPDATE ON public.system_db_table_aliases FOR EACH ROW EXECUTE FUNCTION public.set_system_db_table_aliases_updated_timestamp();`)
	}
	// 12 is the real-name collision; 13 has a preserved inactive primary row.
	namespaceExec(t, db, `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug,is_primary,is_active,created,updated) VALUES
        (12,'reports',true,true,'2024-02-03 04:05:06','2025-03-04 05:06:07'),
        (13,'inactive-beta',false,false,'2024-02-03 04:05:06','2025-03-04 05:06:07');`)
	raw, err := os.ReadFile(filepath.Join("..", "..", "..", "server_tools", "migrations", namespaceMigration))
	if err != nil {
		t.Fatal(err)
	}
	namespaceExec(t, db, string(raw))
	// Supervisor-only mutation proof: the same assertions must fail with the
	// cross-table serialization guarantee removed, even with row guards intact.
	if os.Getenv("FILTEREST_NAMESPACE_COUNTERPROOF") == "1" {
		namespaceExec(t, db, `CREATE OR REPLACE FUNCTION public.app_lock_dataset_namespace() RETURNS void LANGUAGE plpgsql AS $$ BEGIN RETURN; END; $$;`)
	}
	return db
}

func namespaceExec(t *testing.T, q interface {
	Exec(string, ...any) (sql.Result, error)
}, statement string, args ...any) {
	t.Helper()
	if _, err := q.Exec(statement, args...); err != nil {
		t.Fatal(err)
	}
}

func TestDatasetNamespacePostgresAuditBothOriginsAndReplay(t *testing.T) {
	for _, legacy := range []bool{false, true} {
		t.Run(fmt.Sprintf("legacy_%t", legacy), func(t *testing.T) {
			db := namespacePostgres(t, legacy)
			raw, err := os.ReadFile(filepath.Join("..", "..", "..", "server_tools", "migrations", namespaceMigration))
			if err != nil {
				t.Fatal(err)
			}
			var before string
			if err := db.QueryRow(`SELECT jsonb_agg(to_jsonb(a) ORDER BY id)::text FROM public.system_db_table_aliases a`).Scan(&before); err != nil {
				t.Fatal(err)
			}
			namespaceExec(t, db, string(raw))
			var after string
			if err := db.QueryRow(`SELECT jsonb_agg(to_jsonb(a) ORDER BY id)::text FROM public.system_db_table_aliases a`).Scan(&after); err != nil {
				t.Fatal(err)
			}
			if before != after {
				t.Fatalf("replay altered alias rows/timestamps: %s / %s", before, after)
			}
			var active, primary bool
			var reason, created, updated string
			if err := db.QueryRow(`SELECT is_active,is_primary,disabled_reason,created::text,updated::text FROM public.system_db_table_aliases WHERE alias_slug='reports'`).Scan(&active, &primary, &reason, &created, &updated); err != nil {
				t.Fatal(err)
			}
			if active || primary || reason != "dataset_namespace_real_name_conflict" || !strings.HasPrefix(created, "2024-02-03 04:05:06") || !strings.HasPrefix(updated, "2025-03-04 05:06:07") {
				t.Fatalf("audit did not preserve collision history: %v/%v/%s/%s/%s", active, primary, reason, created, updated)
			}
			var real, records, keys int
			if err := db.QueryRow(`SELECT count(*) FROM public.system_db_tables WHERE table_name='Reports'`).Scan(&real); err != nil {
				t.Fatal(err)
			}
			if err := db.QueryRow(`SELECT count(*) FROM public.system_data_repair_records WHERE migration='wl159_dataset_namespace'`).Scan(&records); err != nil {
				t.Fatal(err)
			}
			if err := db.QueryRow(`SELECT count(*) FROM public.system_lang_key_translations WHERE language_code IN ('en','fi','ch','yue')`).Scan(&keys); err != nil {
				t.Fatal(err)
			}
			if real != 1 || records != 1 || keys != 32 {
				t.Fatalf("audit/translation completion differs: %d/%d/%d", real, records, keys)
			}
			snapshot, err := LoadDatasetAliasManagementSnapshot(db)
			if err != nil {
				t.Fatal(err)
			}
			entry, err := findAliasManagementEntry(snapshot, "system_alpha")
			if err != nil || !reflect.DeepEqual(entry.DisabledAliases, []DisabledDatasetAlias{{"reports", "dataset_namespace_real_name_conflict"}}) {
				t.Fatalf("administrator notice absent: %+v %v", entry, err)
			}
			if got := ResolveRawDatasetNameWithQuerier(db, "REPORTS"); got != "Reports" {
				t.Fatalf("disabled alias took real name: %s", got)
			}
			if _, err := SavePrimaryAlias(db, "system_alpha", "free-alpha"); err != nil {
				t.Fatal(err)
			}
			if _, err := SavePrimaryAlias(db, "system_alpha", ""); err != nil {
				t.Fatal(err)
			}
			var preserved int
			if err := db.QueryRow(`SELECT count(*) FROM public.system_db_table_aliases WHERE alias_slug='reports' AND disabled_reason IS NOT NULL`).Scan(&preserved); err != nil || preserved != 1 {
				t.Fatalf("save/clear deleted disabled audit row: %d %v", preserved, err)
			}
		})
	}
}

func TestDatasetNamespacePostgresConcurrentAliasCreateRename(t *testing.T) {
	cases := []struct{ name, first, second string }{
		{"alias_then_create", `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`,
			`CREATE TABLE public."Claimed"(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'Claimed')`},
		{"create_then_alias", `CREATE TABLE public."Claimed"(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'Claimed')`,
			`INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`},
		{"alias_then_automatic_name", `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`,
			`CREATE TABLE public.app_Claimed(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'app_Claimed')`},
		{"automatic_name_then_alias", `CREATE TABLE public.app_Claimed(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'app_Claimed')`,
			`INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`},
		{"alias_then_rename", `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`,
			`ALTER TABLE public."Reports" RENAME TO "Claimed"; UPDATE public.system_db_tables SET table_name='Claimed' WHERE table_uid=11`},
		{"rename_then_alias", `ALTER TABLE public."Reports" RENAME TO "Claimed"; UPDATE public.system_db_tables SET table_name='Claimed' WHERE table_uid=11`,
			`INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`},
		{"two_alias_saves", `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug,is_primary) VALUES(12,'claimed',true)`,
			`INSERT INTO public.system_db_table_aliases(table_uid,alias_slug,is_primary) VALUES(13,'claimed',true)`},
		{"two_real_names", `CREATE TABLE public."Claimed"(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'Claimed')`,
			`CREATE TABLE public.claimed(id integer); INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(15,'claimed')`},
	}
	for _, fixture := range cases {
		t.Run(fixture.name, func(t *testing.T) {
			db := namespacePostgres(t, false)
			namespaceRace(t, db, fixture.first, fixture.second, sql.LevelReadCommitted)
			assertSingleNamespaceOwner(t, db, "claimed")
		})
	}
}

func TestDatasetNamespacePostgresStaleRepeatableReadRefuses(t *testing.T) {
	db := namespacePostgres(t, false)
	namespaceRace(t, db, `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(12,'claimed')`,
		`INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'Claimed')`, sql.LevelRepeatableRead)
	assertSingleNamespaceOwner(t, db, "claimed")
}

func namespaceRace(t *testing.T, db *sql.DB, first, second string, isolation sql.IsolationLevel) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	tx1, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatal(err)
	}
	defer tx1.Rollback()
	tx2, err := db.BeginTx(ctx, &sql.TxOptions{Isolation: isolation})
	if err != nil {
		t.Fatal(err)
	}
	defer tx2.Rollback()
	var pid int
	// Establish RR's snapshot before the other writer changes the witness.
	if err := tx2.QueryRowContext(ctx, `SELECT pg_backend_pid(), revision FROM public.system_dataset_namespace_lock`).Scan(&pid, new(int64)); err != nil {
		t.Fatal(err)
	}
	namespaceExec(t, tx1, first)
	done := make(chan error, 1)
	go func() {
		_, err := tx2.ExecContext(ctx, second)
		if err == nil {
			err = tx2.Commit()
		}
		done <- err
	}()
	deadline := time.Now().Add(4 * time.Second)
	for {
		select {
		case err := <-done:
			t.Fatalf("counterproof: concurrent writer did not wait for namespace lock: %v", err)
		default:
		}
		var waiting bool
		if err := db.QueryRowContext(ctx, `SELECT EXISTS(SELECT 1 FROM pg_locks WHERE pid=$1 AND locktype='advisory' AND classid=159 AND objid=284 AND NOT granted)`, pid).Scan(&waiting); err != nil {
			t.Fatal(err)
		}
		if waiting {
			break
		}
		if time.Now().After(deadline) {
			t.Fatal("concurrent writer never reached the shared namespace lock")
		}
		time.Sleep(10 * time.Millisecond)
	}
	if err := tx1.Commit(); err != nil {
		t.Fatal(err)
	}
	err = <-done
	var pg *pq.Error
	if !errors.As(err, &pg) || !(pg.Code == "P0001" && pg.Message == NamespaceConflictKey || isolation == sql.LevelRepeatableRead && pg.Code == "40001") {
		t.Fatalf("expected stable namespace conflict or stale snapshot refusal, got %v", err)
	}
	t.Logf("blocked competing writer, then refused with SQLSTATE %s", pg.Code)
}

func assertSingleNamespaceOwner(t *testing.T, db *sql.DB, name string) {
	t.Helper()
	var owners int
	if err := db.QueryRow(`SELECT count(DISTINCT table_uid) FROM (
        SELECT table_uid FROM public.system_db_tables WHERE public.app_dataset_name_key(table_name)=$1
        UNION ALL SELECT table_uid FROM public.system_db_tables WHERE public.app_dataset_name_key(table_name)='app_' || $1
        UNION ALL SELECT table_uid FROM public.system_db_table_aliases WHERE is_active IS TRUE AND public.app_dataset_name_key(alias_slug)=$1
    ) names`, name).Scan(&owners); err != nil || owners != 1 {
		t.Fatalf("two datasets own one folded name: owners=%d err=%v", owners, err)
	}
}

func TestDatasetNamespacePostgresSecondaryReservedDeleteAndClear(t *testing.T) {
	db := namespacePostgres(t, false)
	namespaceExec(t, db, `INSERT INTO public.system_db_table_aliases(table_uid,alias_slug,is_primary) VALUES(12,'old_alpha',false)`)
	for _, statement := range []string{
		`INSERT INTO public.system_db_tables(table_uid,table_name) VALUES(14,'OLD_ALPHA')`,
		`INSERT INTO public.system_db_table_aliases(table_uid,alias_slug) VALUES(13,'old_alpha')`,
		`UPDATE public.system_db_tables SET table_name='API' WHERE table_uid=13`,
	} {
		_, err := db.Exec(statement)
		var pg *pq.Error
		if !errors.As(err, &pg) || pg.Message != NamespaceConflictKey {
			t.Fatalf("secondary/reserved name accepted: %s %v", statement, err)
		}
	}
	// Delete/cascade releases every alias in the same transaction; explicit
	// primary clear leaves secondary names in place.
	if _, err := SavePrimaryAlias(db, "system_alpha", "new-alpha"); err != nil {
		t.Fatal(err)
	}
	if _, err := SavePrimaryAlias(db, "system_alpha", ""); err != nil {
		t.Fatal(err)
	}
	if got := ResolveRawDatasetNameWithQuerier(db, "old_alpha"); got != "system_alpha" {
		t.Fatal("clear removed secondary alias", got)
	}
	namespaceExec(t, db, `DELETE FROM public.system_db_tables WHERE table_uid=12`)
	if _, err := SavePrimaryAlias(db, "system_beta", "old_alpha"); err != nil {
		t.Fatal("delete failed to release namespace", err)
	}
}
