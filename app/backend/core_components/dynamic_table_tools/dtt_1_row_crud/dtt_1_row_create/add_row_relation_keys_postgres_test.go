// Reuse WL124's cluster, account/read-policy fixture and session. Probe the socket
// boundary first so a sandbox without socket permission skips instead of failing.
func relationKeysPostgres(t *testing.T) *sql.DB {
	t.Helper()
	if os.Getenv("FILTEREST_TEST_DISPOSABLE_POSTGRES") != "1" {
		t.Skip("set FILTEREST_TEST_DISPOSABLE_POSTGRES=1")
	}
	listener, err := net.Listen("unix", filepath.Join(t.TempDir(), "probe"))
	if err != nil {
		if strings.Contains(err.Error(), "operation not permitted") || strings.Contains(err.Error(), "permission denied") {
			t.Skip("sandbox refuses disposable PostgreSQL Unix sockets")
		}
		t.Fatal(err)
	}
	_ = listener.Close()
	owner, _ := raceCluster(t)
	original := backend.Db
	backend.Db = owner
	t.Cleanup(func() { backend.Db = original })
	raceExec(t, owner, relationKeysFixture)
	return owner
}

