func TestCreateNonIDRelationsAndNestedUploadPostgres(t *testing.T) {
	db := relationKeysPostgres(t)
	request := raceRequest(t)
	for _, bridgeID := range []int64{100, 101} {
		t.Run("bridge orientation "+string(rune('A'+bridgeID-100)), func(t *testing.T) {
			tx, err := db.Begin()
			if err != nil {
				t.Fatal(err)
			}
			defer tx.Rollback()
			payload := map[string]interface{}{
				"title": "new parent",
				"_childRows": []ChildRowPayload{
					{RelationID: 52, Data: map[string]interface{}{}},
					{RelationID: 53, Data: map[string]interface{}{}},
				},
				"_existingLinks": []ExistingRelationLinkPayload{
					{RelationKind: existingRelationOneToMany, RelationID: 50, RowIDs: []int64{7}},
					{RelationKind: existingRelationOneToMany, RelationID: 51, RowIDs: []int64{8}},
					{RelationKind: existingRelationManyToMany, RelationID: bridgeID, RowIDs: []int64{11}},
				},
			}
			response := httptest.NewRecorder()
			id, children, err := insertDataAccordingToPayload(response, request, "review_notes", "20", payload, tx)
			if err != nil {
				t.Fatalf("create response=%d %s error=%v", response.Code, response.Body.String(), err)
			}
			var correct bool
			if err := tx.QueryRow(`SELECT
                (SELECT parent_key=9044 FROM linked_children WHERE id=7) AND
                (SELECT parent_key=p.slug FROM text_children WHERE id=8) AND
                (SELECT parent_key=9044 FROM owned_docs WHERE id=$2) AND
                (SELECT parent_key=p.slug AND position IS NULL FROM owned_locations WHERE id=$3) AND
                (SELECT parent_key=9044 AND tag_key='9044' FROM key_bridge)
                FROM review_notes p WHERE p.id=$1`, id, children[0].ChildRowID, children[1].ChildRowID).Scan(&correct); err != nil || !correct {
				t.Fatalf("stored reference checks=%v error=%v", correct, err)
			}
			var body bytes.Buffer
			writer := multipart.NewWriter(&body)
			part, err := writer.CreateFormFile("file_child_0", "fixture.pdf")
			if err != nil {
				t.Fatal(err)
			}
			_, _ = part.Write([]byte("%PDF-1.7\nsynthetic reference fixture\n"))
			_ = writer.Close()
			form, err := multipart.NewReader(&body, writer.Boundary()).ReadForm(1024)
			if err != nil {
				t.Fatal(err)
			}
			defer form.RemoveAll()
			if err := saveUploadedFiles(request.Context(), tx, response, form.File, t.TempDir(), "review_notes", "20", id, children); err != nil {
				t.Fatalf("upload response=%d %s error=%v", response.Code, response.Body.String(), err)
			}
			if err := tx.QueryRow(`SELECT p.uploaded_filename=d.filename AND
                (SELECT uploaded_filename='untouched' FROM review_notes WHERE id=9044)
                FROM review_notes p JOIN owned_docs d ON d.parent_key=p.table_uid WHERE p.id=$1`, id).Scan(&correct); err != nil || !correct {
				t.Fatalf("only intended upload cache changed=%v error=%v", correct, err)
			}
		})
	}
}

func TestCreateMissingReferenceRollsBackEarlierWritesPostgres(t *testing.T) {
	db := relationKeysPostgres(t)
	request := raceRequest(t)
	for _, missingParent := range []bool{false, true} {
		t.Run(map[bool]string{false: "related NULL after earlier links", true: "parent NULL after earlier child"}[missingParent], func(t *testing.T) {
			if missingParent {
				raceExec(t, db, `UPDATE system_foreign_key_relations_1_m SET target_column_name='nullable_key' WHERE id=53`)
			}
			tx, err := db.Begin()
			if err != nil {
				t.Fatal(err)
			}
			defer tx.Rollback()
			payload := map[string]interface{}{"title": "refused parent",
				"_childRows": []ChildRowPayload{{RelationID: 52, Data: map[string]interface{}{}}, {RelationID: 53, Data: map[string]interface{}{}}},
				"_existingLinks": []ExistingRelationLinkPayload{
					{RelationKind: existingRelationOneToMany, RelationID: 50, RowIDs: []int64{7}},
					{RelationKind: existingRelationManyToMany, RelationID: 100, RowIDs: []int64{11}},
					{RelationKind: existingRelationManyToMany, RelationID: 102, RowIDs: []int64{11}},
				}}
			response := httptest.NewRecorder()
			_, _, err = insertDataAccordingToPayload(response, request, "review_notes", "20", payload, tx)
			if err == nil || response.Code != 400 || !strings.Contains(response.Body.String(), "error_relation_reference_missing") {
				t.Fatalf("missing key refusal=%v response=%d %s", err, response.Code, response.Body.String())
			}
			if err := tx.Rollback(); err != nil {
				t.Fatal(err)
			}
			var clean bool
			if err := db.QueryRow(`SELECT
                (SELECT count(*)=1 FROM review_notes) AND
                (SELECT count(*)=0 FROM owned_docs) AND
                (SELECT count(*)=0 FROM owned_locations) AND
                (SELECT count(*)=0 FROM key_bridge) AND
                (SELECT count(*)=0 FROM null_bridge) AND
                (SELECT parent_key IS NULL FROM linked_children WHERE id=7)`).Scan(&clean); err != nil || !clean {
				t.Fatalf("full rollback=%v error=%v", clean, err)
			}
		})
	}
}

func TestCreateRelationAuthorizationUsesPhysicalIDPostgres(t *testing.T) {
	db := relationKeysPostgres(t)
	request := raceRequest(t)
	// A reference value that exists is not a selectable physical row identifier.
	var payload map[string]interface{}
	_ = json.Unmarshal([]byte(`{"title":"guessed key","_existingLinks":[{"relationKind":"many_to_many","relationId":100,"rowIds":[9044]}]}`), &payload)
	tx, err := db.Begin()
	if err != nil {
		t.Fatal(err)
	}
	defer tx.Rollback()
	response := httptest.NewRecorder()
	_, _, err = insertDataAccordingToPayload(response, request, "review_notes", "20", payload, tx)
	if err == nil || response.Code != 403 || !strings.Contains(response.Body.String(), relatedRowsUnreadable) {
		t.Fatalf("physical-id authorization refusal=%v response=%d %s", err, response.Code, response.Body.String())
	}
}

func TestCreateReadDeniedNonIDTargetMatchesMissingPostgres(t *testing.T) {
	db := relationKeysPostgres(t)
	originalBasic := backend.DbBasic
	backend.DbBasic = db
	defer func() { backend.DbBasic = originalBasic }()
	const secretReference = "private-reference-canary"
	raceExec(t, db, `UPDATE linked_tags SET slug=$1 WHERE id=11`, secretReference)
	raceExec(t, db, `INSERT INTO system_row_access_rules (table_uid,action_id,row_id,user_id,effect)
        VALUES (40,1,11,4,'deny')`)
	var exists bool
	if err := db.QueryRow(`SELECT EXISTS (SELECT 1 FROM linked_tags WHERE id=11 AND slug=$1)`, secretReference).Scan(&exists); err != nil || !exists {
		t.Fatalf("read-denied target must exist with its non-id key: %v %v", exists, err)
	}
	before := relationRowsSnapshot(t, db)
	request := raceRequest(t)
	var missingBody string
	for _, rowID := range []int64{99999, 11} {
		response := httptest.NewRecorder()
		handler := middlewares.WithLazyTransaction(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			tx, ok := dbutils.RequireTx(r.Context())
			if !ok {
				t.Fatal("request transaction did not start")
			}
			payload := map[string]interface{}{"title": "hidden reference",
				"_existingLinks": []ExistingRelationLinkPayload{
					{RelationKind: existingRelationManyToMany, RelationID: 100, RowIDs: []int64{rowID}},
				}}
			if _, _, err := insertDataAccordingToPayload(w, r, "review_notes", "20", payload, tx); err == nil {
				t.Fatal("unreadable related row was accepted")
			}
		}))
		handler.ServeHTTP(response, request)
		body := response.Body.String()
		if response.Code != http.StatusForbidden || !strings.Contains(body, relatedRowsUnreadable) || strings.Contains(body, secretReference) {
			t.Fatalf("unreadable related-row response=%d %s", response.Code, body)
		}
		if rowID == 99999 {
			missingBody = body
		} else if body != missingBody {
			t.Fatalf("read denial reveals whether the target exists: missing=%s denied=%s", missingBody, body)
		}
		if relationRowsSnapshot(t, db) != before {
			t.Fatal("read denial left main, child, bridge or cache writes")
		}
	}
}
