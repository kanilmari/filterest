// rename_tree_node_postgres_test.go
// Proves both tree rename routes on disposable PostgreSQL: the label moves, nothing shared changes.
// Connects renameFolder and renameTable to the language component and the source rewrite helpers.
// Opt-in precedes cluster creation; installation databases are never consulted.
package dtt_system_table_folders

