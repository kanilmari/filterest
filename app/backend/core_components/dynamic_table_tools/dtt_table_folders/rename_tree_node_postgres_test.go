func renameInTransaction(t *testing.T, db *sql.DB, rename func(*sql.Tx) (lang.ItemLabelOutcome, error)) lang.ItemLabelOutcome {
	t.Helper()
	tx, err := db.Begin()
	if err != nil {
		t.Fatal(err)
	}
	outcome, err := rename(tx)
	if err != nil {
		_ = tx.Rollback()
		t.Fatal(err)
	}
	if err := tx.Commit(); err != nil {
		t.Fatal(err)
	}
	return outcome
}

func sourceList(t *testing.T, db *sql.DB, langKey string) string {
	t.Helper()
	var list sql.NullString
	if err := db.QueryRow(`SELECT string_agg(s.source_type || ':' || s.source_high || ':' || s.source_low, ', '
		ORDER BY s.source_type, s.source_high) FROM system_lang_key_sources s JOIN system_lang_keys k ON k.id = s.lang_key_id
		WHERE k.lang_key = $1`, langKey).Scan(&list); err != nil {
		t.Fatal(err)
	}
	return list.String
}

func explanationOf(t *testing.T, db *sql.DB, sourceType, sourceHigh string) string {
	t.Helper()
	var explanation string
	if err := db.QueryRow(`SELECT usage_explanation FROM system_lang_key_sources WHERE source_type = $1 AND source_high = $2`,
		sourceType, sourceHigh).Scan(&explanation); err != nil {
		t.Fatalf("%s %s: %v", sourceType, sourceHigh, err)
	}
	return explanation
}

func keyText(t *testing.T, db *sql.DB, langKey string) string {
	t.Helper()
	var text sql.NullString
	if err := db.QueryRow(`SELECT concat_ws('|', k.fi, k.en, k.ch, k.yue, (SELECT string_agg(r.language_code || '=' || r.translation, ',' ORDER BY r.language_code)
		FROM system_lang_key_translations r WHERE r.lang_key_id = k.id)) FROM system_lang_keys k WHERE k.lang_key = $1`, langKey).Scan(&text); err != nil {
		t.Fatalf("%s: %v", langKey, err)
	}
	return text.String
}

func TestTreeFolderRenameKeepsANameAnotherFolderStillHasPostgres(t *testing.T) {
	db := renamePostgresDB(t)
	before := keyText(t, db, "reports")

	renameInTransaction(t, db, func(tx *sql.Tx) (lang.ItemLabelOutcome, error) {
		return renameFolder(tx, RenameTreeNodeRequest{ItemID: 2, ItemType: "folder", NewName: "monthly_reports",
			Translations:      map[string]string{"fi": "Kuukausiraportit", "en": "Reports"},
			ShownTranslations: map[string]string{"fi": "Raportit", "en": "Reports"}})
	})
	if got := sourceList(t, db, "reports"); got != "folder:reports:reports" {
		t.Fatal("the other folder lost its label association:", got)
	}
	if got := keyText(t, db, "reports"); got != before {
		t.Fatal("the shared key changed:", got)
	}
	if got := sourceList(t, db, "monthly_reports"); got != "folder:monthly_reports:monthly_reports" {
		t.Fatal(got)
	}
	if got := keyText(t, db, "monthly_reports"); got != "Kuukausiraportit|Reports|报告|報告|fi=Kuukausiraportit,zh-TW=Raportit (TW)" {
		t.Fatal("new key:", got)
	}

	// Renaming the last folder of a name moves its association and the usage explanation.
	renameInTransaction(t, db, func(tx *sql.Tx) (lang.ItemLabelOutcome, error) {
		return renameFolder(tx, RenameTreeNodeRequest{ItemID: 3, ItemType: "folder", NewName: "notes"})
	})
	if got := sourceList(t, db, "drafts"); got != "code:frontend/drafts.js:" {
		t.Fatal("old key keeps only other users:", got)
	}
	if got := explanationOf(t, db, "code", "frontend/drafts.js"); got != "Folder 'drafts'" {
		t.Fatal("another source's explanation was rewritten:", got)
	}
	var explanation string
	if err := db.QueryRow(`SELECT usage_explanation FROM system_lang_key_sources WHERE source_type = 'folder' AND source_high = 'notes'`).Scan(&explanation); err != nil || explanation != "Folder 'notes'" {
		t.Fatal(explanation, err)
	}
	if got := keyText(t, db, "notes"); got != "Luonnokset|Drafts|草稿|zh-TW=Luonnokset (TW)" {
		t.Fatal("new key:", got)
	}
}

func TestTreeTableRenameMovesOnlyThisDatasetsSourcesPostgres(t *testing.T) {
	db := renamePostgresDB(t)
	before := keyText(t, db, "a_b")

	renameInTransaction(t, db, func(tx *sql.Tx) (lang.ItemLabelOutcome, error) {
		return renameTable(tx, RenameTreeNodeRequest{ItemID: 10, ItemType: "table", NewName: "c_d",
			Translations: map[string]string{"fi": "Ab-taulu", "en": "Cd table"}})
	})
	var registered string
	if err := db.QueryRow(`SELECT table_name FROM system_db_tables WHERE id = 10`).Scan(&registered); err != nil || registered != "c_d" {
		t.Fatal(registered, err)
	}
	if got := keyText(t, db, "a_b"); got != before {
		t.Fatal("old dataset key changed:", got)
	}
	if got := sourceList(t, db, "a_b"); got != "code:frontend/ab_widget.js:" {
		t.Fatal("old key sources:", got)
	}
	if got := keyText(t, db, "c_d"); got != "Ab-taulu|Cd table|甲乙|en=Cd table,zh-TW=Ab-taulu (TW)" {
		t.Fatal("new key:", got)
	}
	if got := sourceList(t, db, "c_d"); got != "table:c_d:c_d" {
		t.Fatal(got)
	}
	// The dataset's column sources follow it; the look-alike "axb" keeps every source.
	if got := sourceList(t, db, "status"); got != "code:frontend/status.js:, column:axb:status, column:c_d:status, column_value:axb.status:, column_value:c_d.status:, dataset_header:axb:status:" {
		t.Fatal("column sources:", got)
	}
	// Only the dataset's own explanations are rewritten.
	for _, check := range []struct{ kind, high, want string }{
		{"table", "c_d", "Table 'c_d'"},
		{"column", "c_d", "Column 'status' in table 'c_d'"},
		{"column", "axb", "Column 'status' in table 'axb'"},
		{"code", "frontend/ab_widget.js", "Table 'a_b'"},
		{"code", "frontend/status.js", "Status column 'a_b.status' in table 'a_b'"},
	} {
		if got := explanationOf(t, db, check.kind, check.high); got != check.want {
			t.Fatal(check.kind, check.high, got)
		}
	}

	// The registry cell edit calls the same move without typed text.
	renameInTransaction(t, db, func(tx *sql.Tx) (lang.ItemLabelOutcome, error) {
		return renameTable(tx, RenameTreeNodeRequest{ItemID: 10, ItemType: "table", NewName: "e_f"})
	})
	if got := keyText(t, db, "e_f"); got != "Ab-taulu|Cd table|甲乙|en=Cd table,zh-TW=Ab-taulu (TW)" {
		t.Fatal("key copied without typed text:", got)
	}
	if got := sourceList(t, db, "c_d"); got != "" {
		t.Fatal("the intermediate key kept the dataset's source:", got)
	}
	if got := sourceList(t, db, "e_f"); got != "table:e_f:e_f" {
		t.Fatal(got)
	}
}
