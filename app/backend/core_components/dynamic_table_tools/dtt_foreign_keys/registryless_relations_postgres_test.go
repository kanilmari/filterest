// registryless_relations_postgres_test.go
// Exercises startup discovery of registry-less relations on disposable PostgreSQL.
// Connects catalog FKs, registry-less metadata and registered-row snapshots.
// Proves replay safety without accessing an installation's database or settings.
package dtt_foreign_keys

