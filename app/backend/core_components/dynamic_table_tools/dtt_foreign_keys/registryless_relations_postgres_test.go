func registrylessPostgres(t *testing.T) *sql.DB {
	t.Helper()
	if os.Getenv("FILTEREST_TEST_DISPOSABLE_POSTGRES") != "1" {
		t.Skip("set FILTEREST_TEST_DISPOSABLE_POSTGRES=1 to run isolated PostgreSQL verification")
	}
	root, err := os.MkdirTemp("/tmp", "b505-pg-")
	if err != nil {
		t.Fatal(err)
	}
	bin := os.Getenv("PG_TEST_BIN")
	if bin == "" {
		bin = "/usr/lib/postgresql/16/bin"
	}
	data, socket := filepath.Join(root, "db"), filepath.Join(root, "socket")
	run := func(name string, args ...string) {
		t.Helper()
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		if output, err := exec.CommandContext(ctx, filepath.Join(bin, name), args...).CombinedOutput(); err != nil {
			t.Fatalf("%s: %v: %s", name, err, output)
		}
	}
	// Retain the child process handle and observe its exit before removing
	// paths; a missing pid file alone never proves the server has stopped.
	var server *exec.Cmd
	var exited chan struct{}
	t.Cleanup(func() {
		if exited != nil {
			select {
			case <-exited:
			default:
				_ = server.Process.Signal(syscall.SIGINT)
				select {
				case <-exited:
				case <-time.After(5 * time.Second):
					_ = server.Process.Kill()
					select {
					case <-exited:
					case <-time.After(5 * time.Second):
						t.Errorf("disposable PostgreSQL exit unconfirmed; retained %s", root)
						return
					}
				}
			}
		}
		if err := os.RemoveAll(root); err != nil {
			t.Errorf("remove disposable PostgreSQL: %v", err)
		}
	})
	if err := os.Mkdir(socket, 0o700); err != nil {
		t.Fatal(err)
	}
	run("initdb", "-D", data, "-A", "trust", "-U", "test_owner", "--no-locale", "--encoding=UTF8")
	logPath := filepath.Join(root, "postgres.log")
	logFile, err := os.Create(logPath)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = logFile.Close() })
	// Only this cluster's unique Unix socket is used; no TCP listener or live DSN.
	server = exec.Command(filepath.Join(bin, "postgres"), "-D", data, "-h", "", "-k", socket, "-p", "15487")
	server.Stdout, server.Stderr = logFile, logFile
	if err := server.Start(); err != nil {
		t.Fatal(err)
	}
	exited = make(chan struct{})
	go func() { _ = server.Wait(); close(exited) }()
	db, err := sql.Open("postgres", fmt.Sprintf("host=%s port=15487 user=test_owner dbname=postgres sslmode=disable", socket))
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = db.Close() })
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	for {
		if err := db.PingContext(ctx); err == nil {
			break
		}
		select {
		case <-exited:
			output, _ := os.ReadFile(logPath)
			t.Fatalf("disposable PostgreSQL exited during startup: %s", output)
		case <-ctx.Done():
			output, _ := os.ReadFile(logPath)
			t.Fatalf("disposable PostgreSQL not ready: %v: %s", ctx.Err(), output)
		case <-time.After(50 * time.Millisecond):
		}
	}
	registrylessExec(t, db, registrylessFixture)
	return db
}

func registrylessExec(t *testing.T, db *sql.DB, query string) {
	t.Helper()
	if _, err := db.Exec(query); err != nil {
		t.Fatalf("disposable fixture/migration: %v", err)
	}
}

func registrylessSnapshot(t *testing.T, db *sql.DB, table, predicate string) string {
	t.Helper()
	var result string
	// row_to_json retains all columns, NULLs and timestamp precision. Compare
	// the entire serialized row, not merely ids or selected metadata columns.
	if err := db.QueryRow("SELECT COALESCE(json_agg(row_to_json(r) ORDER BY id)::text, '[]') FROM " + table + " r WHERE " + predicate).Scan(&result); err != nil {
		t.Fatal(err)
	}
	return result
}

func registrylessCount(t *testing.T, db *sql.DB, query string, want int) {
	t.Helper()
	var count int
	if err := db.QueryRow(query).Scan(&count); err != nil || count != want {
		t.Fatalf("%s: count=%d, want=%d, err=%v", query, count, want, err)
	}
}

func TestRegistrylessOneToManySyncPostgres(t *testing.T) {
	db := registrylessPostgres(t)
	// The registered side's uid is part of identity: these lookalikes must
	// neither suppress discovery nor be pruned by either preservation mode.
	registrylessExec(t, db, `INSERT INTO system_foreign_key_relations_1_m
 (source_table_uid,target_table_uid,source_column_name,target_column_name,reference_direction)
 VALUES (NULL,40,'table_uid','table_uid','system_dataset_appearance->system_db_tables'),
 (NULL,10,'id','table_uid','system_dataset_appearance->system_db_tables'),
 (NULL,10,'table_uid','table_uid','wrong->direction');`)
	if err := SyncOneToManyFKConstraints(db, false); err != nil {
		t.Fatal(err)
	}
	registered := registrylessSnapshot(t, db, "system_foreign_key_relations_1_m", "source_table_uid IS NOT NULL AND target_table_uid IS NOT NULL")
	registrylessCount(t, db, "SELECT count(*) FROM system_foreign_key_relations_1_m WHERE source_table_uid=20 AND target_table_uid=10", 1)
	// An obsolete but structurally valid registered relation demonstrates the
	// original preserveLegacy contract, including removal on the false run.
	registrylessExec(t, db, `INSERT INTO system_foreign_key_relations_1_m
 (id,source_table_uid,target_table_uid,source_column_name,target_column_name,reference_direction)
 VALUES (900,20,10,'id','table_uid','legacy');`)
	for i := 0; i < 3; i++ {
		if err := SyncOneToManyFKConstraints(db, true); err != nil {
			t.Fatal(err)
		}
		registrylessCount(t, db, "SELECT count(*) FROM system_foreign_key_relations_1_m WHERE id=900", 1)
	}
	if err := SyncOneToManyFKConstraints(db, false); err != nil {
		t.Fatal(err)
	}
	if after := registrylessSnapshot(t, db, "system_foreign_key_relations_1_m", "source_table_uid IS NOT NULL AND target_table_uid IS NOT NULL"); after != registered {
		t.Fatalf("registered relations changed: before=%s after=%s", registered, after)
	}
	for _, identity := range []string{
		"source_table_uid IS NULL AND target_table_uid=10 AND source_column_name='table_uid' AND target_column_name='table_uid' AND reference_direction='system_dataset_appearance->system_db_tables'",
		"source_table_uid=30 AND target_table_uid IS NULL AND reference_direction='child_of_unregistered->unregistered_parent'",
		"source_table_uid IS NULL AND target_table_uid IS NULL AND reference_direction='unregistered_child->unregistered_parent'",
	} {
		registrylessCount(t, db, "SELECT count(*) FROM system_foreign_key_relations_1_m WHERE "+identity, 1)
	}
	registrylessCount(t, db, "SELECT count(*) FROM system_db_tables WHERE table_name='system_dataset_appearance'", 0)
}

func TestRegistrylessManyToManySyncPostgres(t *testing.T) {
	for _, missing := range []string{"bridge", "endpoint", "both endpoints", "all"} {
		t.Run(missing, func(t *testing.T) {
			db := registrylessPostgres(t)
			// Capture fully registered behavior before exercising each NULL side.
			if err := SyncManyToManyFKConstraints(db, false); err != nil {
				t.Fatal(err)
			}
			registered := registrylessSnapshot(t, db, "system_foreign_key_relations_m_m", "bridging_table_uid=50")
			if missing != "bridge" {
				registrylessExec(t, db, `CREATE TABLE mm_a (id integer PRIMARY KEY);
CREATE TABLE mm_b (id integer PRIMARY KEY);
CREATE TABLE endpoint_join (a_id integer REFERENCES mm_a(id), b_id integer REFERENCES mm_b(id), PRIMARY KEY(a_id,b_id));`)
				if missing != "all" {
					registrylessExec(t, db, "INSERT INTO system_db_tables(table_uid,table_name) VALUES(60,'endpoint_join')")
				}
				if missing == "endpoint" {
					registrylessExec(t, db, "INSERT INTO system_db_tables(table_uid,table_name) VALUES(70,'mm_a')")
				}
			}
			for _, preserve := range []bool{true, true, true, false} {
				if err := SyncManyToManyFKConstraints(db, preserve); err != nil {
					t.Fatal(err)
				}
			}
			registrylessCount(t, db, "SELECT count(*) FROM system_foreign_key_relations_m_m WHERE bridging_table_name='registryless_join'", 1)
			if missing != "bridge" {
				registrylessCount(t, db, "SELECT count(*) FROM system_foreign_key_relations_m_m WHERE bridging_table_name='endpoint_join'", 1)
			}
			if after := registrylessSnapshot(t, db, "system_foreign_key_relations_m_m", "bridging_table_uid=50"); after != registered {
				t.Fatalf("registered many-to-many relation changed: before=%s after=%s", registered, after)
			}
		})
	}
}

// Registry names are unique per schema only (gate 505a): a second schema registering the
// same table names must neither raise at startup nor change any stored relation.
func TestRegistrylessLookupsTolerateDuplicateRegistryNamesPostgres(t *testing.T) {
	db := registrylessPostgres(t)
	for _, sync := range []func(*sql.DB, ...bool) error{SyncOneToManyFKConstraints, SyncManyToManyFKConstraints} {
		if err := sync(db, false); err != nil {
			t.Fatal(err)
		}
	}
	// Legacy lookalikes of registered relations, each with one registry UID missing.
	registrylessExec(t, db, `INSERT INTO system_foreign_key_relations_1_m
 (source_table_uid,target_table_uid,source_column_name,target_column_name,reference_direction)
 VALUES (20,NULL,'table_uid','table_uid','registered_child->system_db_tables');
INSERT INTO system_foreign_key_relations_m_m
 (bridging_table_name,bridging_table_uid,bridging_col_a,bridging_col_b,table_a_uid,table_a_column,table_b_uid,table_b_column)
 VALUES ('registered_join',50,'a_id','b_id',NULL,'table_uid',40,'id');
INSERT INTO system_db_tables(table_uid,table_name,schema_name) VALUES
 (11,'system_db_tables','archive'),(41,'peer','archive'),(51,'registered_join','archive');`)
	oneToMany := registrylessSnapshot(t, db, "system_foreign_key_relations_1_m", "true")
	manyToMany := registrylessSnapshot(t, db, "system_foreign_key_relations_m_m", "true")
	for _, preserve := range []bool{true, false} {
		if err := SyncOneToManyFKConstraints(db, preserve); err != nil {
			t.Fatalf("one-to-many sync with duplicate registry names (preserve=%v): %v", preserve, err)
		}
		if err := SyncManyToManyFKConstraints(db, preserve); err != nil {
			t.Fatalf("many-to-many sync with duplicate registry names (preserve=%v): %v", preserve, err)
		}
	}
	if after := registrylessSnapshot(t, db, "system_foreign_key_relations_1_m", "true"); after != oneToMany {
		t.Fatalf("one-to-many relations changed: before=%s after=%s", oneToMany, after)
	}
	if after := registrylessSnapshot(t, db, "system_foreign_key_relations_m_m", "true"); after != manyToMany {
		t.Fatalf("many-to-many relations changed: before=%s after=%s", manyToMany, after)
	}
}
