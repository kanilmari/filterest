def snapshot(database):
    return database("""SELECT jsonb_build_object(
        'views',(SELECT jsonb_agg(to_jsonb(v) ORDER BY id) FROM system_table_views v),
        'assignments',(SELECT jsonb_agg(to_jsonb(a) ORDER BY id) FROM system_view_field_set_assignments a),
        'rights',(SELECT jsonb_agg(to_jsonb(p) ORDER BY function_id,user_group_id) FROM system_group_table_func_rights p),
        'copy',(SELECT jsonb_agg(to_jsonb(k) ORDER BY id) FROM system_lang_keys k),
        'translations',(SELECT jsonb_agg(to_jsonb(t) ORDER BY lang_key_id,language_code) FROM system_lang_key_translations t),
        'versions',(SELECT jsonb_agg(to_jsonb(v)) FROM system_db_version v)
    )""")

def test_fresh_article_is_independent_and_migration_is_idempotent(database):
    database(SCHEMA)
    old = database("SELECT jsonb_agg(to_jsonb(a) ORDER BY id) FROM system_view_field_set_assignments a")
    database(MIGRATION.read_text())
    assert database("SELECT count(*) FROM system_table_views WHERE view_key='article_view'") == "1"
    assert database("SELECT jsonb_agg(to_jsonb(a) ORDER BY id) FROM system_view_field_set_assignments a") == old
    assert database("SELECT count(*) FROM system_group_table_func_rights") == "4"
    assert database("SELECT count(*) FROM system_lang_key_translations") == "4"
    first = snapshot(database)
    database(MIGRATION.read_text())
    assert snapshot(database) == first

