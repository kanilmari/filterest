"""Verify dataset UI hiding on disposable PostgreSQL, never native or production.

Connects migration and runtime queries with retained rows and permissions.
Protects false defaults, reversible hiding, administrator access and idempotence.
"""
from pathlib import Path
import re
import subprocess
import pytest
from test_field_settings_language_seed import database

ROOT = Path(__file__).resolve().parents[2]
MIGRATION = ROOT / "server_tools/migrations/20260911000001_add_dataset_ui_visibility.sql"
SCHEMA = """
CREATE TABLE system_db_tables (table_uid integer PRIMARY KEY, table_name text, schema_name text, updated timestamptz);
CREATE TABLE system_user_group_memberships (user_id integer, group_id integer);
CREATE TABLE system_functions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text UNIQUE, package text,
 disabled boolean, specific_table_related boolean, url_route_endpoint text, ui_only boolean,
 rate_limit_amount integer, rate_limit_minutes integer, creation_spec text);
CREATE TABLE system_group_table_func_rights (
 user_group_id integer, function_id bigint, target_schema_name text, target_table_uid integer, creation_spec text,
 UNIQUE NULLS NOT DISTINCT(user_group_id,function_id,target_schema_name,target_table_uid));
CREATE TABLE fixture_records (id integer PRIMARY KEY, body text);
INSERT INTO system_db_tables VALUES (11,'fixture_records','public',NULL);
INSERT INTO fixture_records VALUES(1,'retained row'),(2,'another retained row');
INSERT INTO system_user_group_memberships VALUES(7,1),(42,2),(1,3);
INSERT INTO system_functions(name) VALUES('existing read route');
INSERT INTO system_group_table_func_rights VALUES(2,1,'public',11,'existing permission'),(3,1,'public',11,'guest permission');
"""

def query_constant(path, name):
    source = (ROOT / path).read_text()
    return re.search(r"const " + name + r" = `(.*?)`", source, re.S)[1]

def test_visibility_migration_and_hide_restore_preserve_data_and_rights(database):
    database(SCHEMA)
    rows_before = database("SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM fixture_records r")
    rights_before = database("SELECT jsonb_agg(to_jsonb(r) ORDER BY user_group_id) FROM system_group_table_func_rights r")
    database(MIGRATION.read_text())
    assert database("SELECT ui_hidden FROM system_db_tables WHERE table_uid=11") == "f"
    assert database("SELECT jsonb_agg(to_jsonb(r) ORDER BY user_group_id) FROM system_group_table_func_rights r WHERE function_id=1") == rights_before
    assert database("SELECT string_agg(user_group_id::text, ',') FROM system_group_table_func_rights WHERE function_id<>1") == "1"
    policy = query_constant("backend/core_components/dataset_visibility/dataset_ui_visibility.go", "hiddenForUserQuery")
    update = query_constant("backend/core_components/system_table_tools/dataset_ui_visibility.go", "updateDatasetUIVisibilityQuery")
    for hidden in (True, False):
        database(update.replace("$1", "'fixture_records'").replace("$2", "TRUE" if hidden else "FALSE"))
        for user in (1, 42, 7):
            result = database(policy.replace("$1", "'fixture_records'").replace("$2", str(user)))
            assert result == ("t" if hidden and user != 7 else "f")
        assert database("SELECT jsonb_agg(to_jsonb(r) ORDER BY id) FROM fixture_records r") == rows_before
        assert database("SELECT jsonb_agg(to_jsonb(r) ORDER BY user_group_id) FROM system_group_table_func_rights r WHERE function_id=1") == rights_before
    database(update.replace("$1", "'fixture_records'").replace("$2", "TRUE"))
    database(MIGRATION.read_text())
    assert database("SELECT ui_hidden FROM system_db_tables WHERE table_uid=11") == "t"
    assert database("SELECT count(*) FROM system_functions WHERE name='system_table_tools.AdminDatasetUIVisibilityHandler'") == "1"
    assert database("SELECT count(*) FROM system_group_table_func_rights WHERE function_id<>1") == "1"
    database("INSERT INTO system_db_tables(table_uid,table_name,schema_name) VALUES(12,'new_dataset','public')")
    assert database("SELECT ui_hidden FROM system_db_tables WHERE table_uid=12") == "f"

def test_ordinary_dataset_list_excludes_hidden_and_restore_reappears(database):
    database(SCHEMA)
    database(MIGRATION.read_text())
    source = (ROOT / "backend/pipeline/access_control/get_tables_visible_to_user.go").read_text()
    query = re.search(r"db.Query\(`(.*?)`", source, re.S)[1].replace("$1", "42")
    assert database(query) == "11"
    sitemap_source = (ROOT / "backend/core_components/router/seo_meta_builder.go").read_text()
    sitemap_query = re.search(r"SELECT t.table_name, t.updated.*?ORDER BY t.table_name", sitemap_source, re.S)[0]
    assert database(sitemap_query).startswith("fixture_records")
    database("UPDATE system_db_tables SET ui_hidden=TRUE WHERE table_uid=11")
    assert database(sitemap_query) == ""
    assert database(query) == ""
    database("UPDATE system_db_tables SET ui_hidden=FALSE WHERE table_uid=11")
    assert database(query) == "11"


def test_ambiguous_dataset_identity_cannot_hide_multiple_metadata_rows(database):
    database(SCHEMA)
    database(MIGRATION.read_text())
    database("INSERT INTO system_db_tables(table_uid,table_name,schema_name) VALUES(12,'fixture_records',NULL)")
    update = query_constant("backend/core_components/system_table_tools/dataset_ui_visibility.go", "updateDatasetUIVisibilityQuery")
    with pytest.raises(subprocess.CalledProcessError):
        database(update.replace("$1", "'fixture_records'").replace("$2", "TRUE"))
    assert database("SELECT count(*) FROM system_db_tables WHERE ui_hidden") == "0"
