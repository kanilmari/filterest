-- 20261009000079_reconcile_system_database_identity_schema.sql
-- Adopts the native installer's identity schema as shared product schema.
-- Connects bootstrap, legacy upgrades and native setup to one physical definition.
-- Preserves every existing identity value; native setup alone owns the first row.
-- VERSION_DB: 9.10.2
-- VERSION_DB_OWNER: 20261009000099_record_database_release_9_10_2.sql
-- COMPLETION_MARKER: wl167_database_identity_schema
-- FINAL_CHECK: public.app_check_database_identity_schema()

-- The runner and setup execute this file in a transaction. Refuse busy or
-- unexpectedly large relations instead of waiting/scanning under a long lock.
SET LOCAL lock_timeout = '2s';
SET LOCAL statement_timeout = '10s';

CREATE TABLE IF NOT EXISTS public.system_database_identity (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    singleton_key      BOOLEAN     NOT NULL DEFAULT TRUE UNIQUE,
    database_id        VARCHAR(32) NOT NULL UNIQUE DEFAULT md5(random()::text || clock_timestamp()::text),
    database_role      TEXT        NOT NULL DEFAULT 'legacy_unclassified',
    source_database_id VARCHAR(32),
    source_db_version  VARCHAR(20),
    source_app_version VARCHAR(20),
    source_git_commit  VARCHAR(64),
    notes              TEXT        NOT NULL DEFAULT '',
    created            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated            TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_refresh_at    TIMESTAMPTZ
);

-- This catalogue also supplies the bootstrap's repeated acceptance check.
-- Do not cast, truncate, fill or rebuild an incompatible existing column:
-- its values need an explicit preservation decision, not an automatic repair.
CREATE OR REPLACE FUNCTION public.app_check_database_identity_schema()
RETURNS SETOF text LANGUAGE sql STABLE SET search_path = pg_catalog, public AS $check$
    SELECT 'identity column shape differs: ' || expected.column_name
    FROM (VALUES
        ('id', 'bigint', true, 'd', NULL::text),
        ('singleton_key', 'boolean', true, '', 'true'),
        ('database_id', 'character varying(32)', true, '', 'md5(((random())::text || (clock_timestamp())::text))'),
        ('database_role', 'text', true, '', '''legacy_unclassified''::text'),
        ('source_database_id', 'character varying(32)', false, '', NULL),
        ('source_db_version', 'character varying(20)', false, '', NULL),
        ('source_app_version', 'character varying(20)', false, '', NULL),
        ('source_git_commit', 'character varying(64)', false, '', NULL),
        ('notes', 'text', true, '', '''''::text'),
        ('created', 'timestamp with time zone', true, '', 'now()'),
        ('updated', 'timestamp with time zone', true, '', 'now()'),
        ('last_refresh_at', 'timestamp with time zone', false, '', NULL)
    ) AS expected(column_name, column_type, not_null, identity_kind, default_expression)
    LEFT JOIN pg_attribute actual ON actual.attrelid = 'public.system_database_identity'::regclass
        AND actual.attname = expected.column_name AND actual.attnum > 0 AND NOT actual.attisdropped
    LEFT JOIN pg_attrdef defaults ON defaults.adrelid = actual.attrelid AND defaults.adnum = actual.attnum
    WHERE actual.attname IS NULL OR format_type(actual.atttypid, actual.atttypmod) <> expected.column_type
       OR actual.attnotnull <> expected.not_null OR actual.attidentity::text <> expected.identity_kind
       OR actual.attgenerated <> ''
       OR pg_get_expr(defaults.adbin, defaults.adrelid) IS DISTINCT FROM expected.default_expression
    UNION ALL
    SELECT 'identity storage must be an ordinary table with exactly twelve columns'
    WHERE (SELECT count(*) FROM pg_attribute WHERE attrelid = 'public.system_database_identity'::regclass
               AND attnum > 0 AND NOT attisdropped) <> 12
       OR (SELECT relkind FROM pg_class WHERE oid = 'public.system_database_identity'::regclass) <> 'r'
    UNION ALL
    SELECT 'identity constraint differs: ' || expected.constraint_name
    FROM (VALUES ('system_database_identity_pkey', 'PRIMARY KEY (id)'),
                 ('system_database_identity_singleton_key_key', 'UNIQUE (singleton_key)'),
                 ('system_database_identity_database_id_key', 'UNIQUE (database_id)'))
         AS expected(constraint_name, definition)
    WHERE NOT EXISTS (SELECT 1 FROM pg_constraint actual
        WHERE actual.conrelid = 'public.system_database_identity'::regclass
          AND actual.conname = expected.constraint_name AND actual.convalidated
          AND pg_get_constraintdef(actual.oid) = expected.definition)
    UNION ALL
    SELECT 'identity updater differs or is disabled'
    WHERE NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.system_database_identity'::regclass
          AND tgname = 'set_system_database_identity_updated' AND NOT tgisinternal
          AND tgfoid = to_regprocedure('public.set_system_database_identity_updated_timestamp()')
          AND tgtype = 19 AND tgenabled = 'O' AND tgnargs = 0
          AND tgattr::text = '' AND tgqual IS NULL)
    UNION ALL
    SELECT 'identity updater function differs'
    WHERE NOT EXISTS (SELECT 1 FROM pg_proc actual JOIN pg_language language ON language.oid = actual.prolang
        WHERE actual.oid = to_regprocedure('public.set_system_database_identity_updated_timestamp()')
          AND language.lanname = 'plpgsql' AND actual.prorettype = 'trigger'::regtype
          AND NOT actual.prosecdef AND actual.provolatile = 'v' AND actual.proconfig IS NULL
          AND actual.prosrc = E'\nBEGIN\n    NEW.updated = NOW();\n    RETURN NEW;\nEND;\n');
$check$;

DO $reconcile$
DECLARE
    expected record;
    actual record;
    findings text;
BEGIN
    -- Only compatible shapes are repaired in place. Defaults affect FUTURE
    -- inserts, and nullability/keys enforce existing values without rewriting.
    FOR expected IN SELECT * FROM (VALUES
        ('singleton_key', 'true'),
        ('database_id', 'md5(((random())::text || (clock_timestamp())::text))'),
        ('database_role', '''legacy_unclassified''::text'),
        ('source_database_id', NULL::text), ('source_db_version', NULL),
        ('source_app_version', NULL), ('source_git_commit', NULL),
        ('notes', '''''::text'), ('created', 'now()'), ('updated', 'now()'),
        ('last_refresh_at', NULL)
    ) AS defaults(column_name, expression)
    LOOP
        SELECT pg_get_expr(adbin, adrelid) AS expression INTO actual
        FROM pg_attribute LEFT JOIN pg_attrdef ON adrelid = attrelid AND adnum = attnum
        WHERE attrelid = 'public.system_database_identity'::regclass AND attname = expected.column_name
          AND attnum > 0 AND NOT attisdropped;
        IF FOUND AND actual.expression IS DISTINCT FROM expected.expression THEN
            IF expected.expression IS NULL THEN
                EXECUTE format('ALTER TABLE public.system_database_identity ALTER COLUMN %I DROP DEFAULT', expected.column_name);
            ELSE
                EXECUTE format('ALTER TABLE public.system_database_identity ALTER COLUMN %I SET DEFAULT %s',
                               expected.column_name, expected.expression);
            END IF;
        END IF;
    END LOOP;
    FOR expected IN SELECT * FROM (VALUES
        ('id', true), ('singleton_key', true), ('database_id', true), ('database_role', true),
        ('source_database_id', false), ('source_db_version', false), ('source_app_version', false),
        ('source_git_commit', false), ('notes', true), ('created', true), ('updated', true), ('last_refresh_at', false)
    ) AS columns(column_name, not_null)
    LOOP
        SELECT attnotnull INTO actual FROM pg_attribute
        WHERE attrelid = 'public.system_database_identity'::regclass AND attname = expected.column_name
          AND attnum > 0 AND NOT attisdropped;
        IF FOUND AND actual.attnotnull <> expected.not_null THEN
            EXECUTE format('ALTER TABLE public.system_database_identity ALTER COLUMN %I %s NOT NULL',
                           expected.column_name, CASE WHEN expected.not_null THEN 'SET' ELSE 'DROP' END);
        END IF;
    END LOOP;
    FOR expected IN SELECT * FROM (VALUES
        ('system_database_identity_pkey', 'PRIMARY KEY (id)'),
        ('system_database_identity_singleton_key_key', 'UNIQUE (singleton_key)'),
        ('system_database_identity_database_id_key', 'UNIQUE (database_id)')
    ) AS constraints(constraint_name, definition)
    LOOP
        IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'public.system_database_identity'::regclass
                         AND conname = expected.constraint_name) THEN
            EXECUTE format('ALTER TABLE public.system_database_identity ADD CONSTRAINT %I %s',
                           expected.constraint_name, expected.definition);
        END IF;
    END LOOP;

    -- Keep the exact installer body and its invoker security. Replacing an
    -- existing function preserves its owner/ACL; do not drop it or add grants.
    -- The alias differs from the record variable "actual" above, which PL/pgSQL would substitute here.
    IF NOT EXISTS (SELECT 1 FROM pg_proc updater JOIN pg_language language ON language.oid = updater.prolang
        WHERE updater.oid = to_regprocedure('public.set_system_database_identity_updated_timestamp()')
          AND language.lanname = 'plpgsql' AND updater.prorettype = 'trigger'::regtype
          AND NOT updater.prosecdef AND updater.provolatile = 'v' AND updater.proconfig IS NULL
          AND updater.prosrc = E'\nBEGIN\n    NEW.updated = NOW();\n    RETURN NEW;\nEND;\n') THEN
        EXECUTE $definition$CREATE OR REPLACE FUNCTION public.set_system_database_identity_updated_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql VOLATILE SECURITY INVOKER$definition$;
        ALTER FUNCTION public.set_system_database_identity_updated_timestamp() RESET ALL;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger
        WHERE tgrelid = 'public.system_database_identity'::regclass
          AND tgname = 'set_system_database_identity_updated' AND NOT tgisinternal
          AND tgfoid = 'public.set_system_database_identity_updated_timestamp()'::regprocedure
          AND tgtype = 19 AND tgenabled = 'O' AND tgnargs = 0
          AND tgattr::text = '' AND tgqual IS NULL) THEN
        DROP TRIGGER IF EXISTS set_system_database_identity_updated ON public.system_database_identity;
        CREATE TRIGGER set_system_database_identity_updated
            BEFORE UPDATE ON public.system_database_identity
            FOR EACH ROW EXECUTE FUNCTION public.set_system_database_identity_updated_timestamp();
    END IF;

    SELECT string_agg(finding, '; ') INTO findings FROM public.app_check_database_identity_schema() finding;
    IF findings IS NOT NULL THEN
        RAISE EXCEPTION 'database identity schema reconciliation refused: %', findings;
    END IF;

    -- Old dump setup can reach this file before the shared repair ledger exists.
    -- Startup replays the migration through the runner after support migrations;
    -- normal upgrades/bootstrap always record this idempotent completion mark.
    IF to_regclass('public.system_data_repair_records') IS NOT NULL THEN
        INSERT INTO public.system_data_repair_records (migration, action)
        SELECT 'wl167_database_identity_schema', 'completed'
        WHERE NOT EXISTS (SELECT 1 FROM public.system_data_repair_records
                          WHERE migration = 'wl167_database_identity_schema' AND action = 'completed');
    END IF;
END $reconcile$;
