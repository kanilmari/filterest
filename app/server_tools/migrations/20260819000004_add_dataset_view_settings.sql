-- 20260819000004_add_dataset_view_settings.sql
-- Adds normalized, versioned presentation settings for individual datasets.
-- The first consumer is the article view; later presentations can add their
-- own allowlisted configuration without widening system_db_tables repeatedly.
-- VERSION_DB: 9.2.0
-- VERSION_DB_OWNER: 20260819000003_record_dataset_media_db_release.sql

CREATE TABLE IF NOT EXISTS public.system_dataset_view_settings (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_uid        INTEGER     NOT NULL
        REFERENCES public.system_db_tables(table_uid) ON DELETE CASCADE,
    presentation     TEXT        NOT NULL DEFAULT 'article',
    config_version   INTEGER     NOT NULL DEFAULT 1,
    article_variant  TEXT        NOT NULL DEFAULT 'standard',
    details_position TEXT        NOT NULL DEFAULT 'after_description',
    created          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_system_dataset_view_settings_presentation
        CHECK (presentation IN ('article')),
    CONSTRAINT ck_system_dataset_view_settings_config_version
        CHECK (config_version >= 1),
    CONSTRAINT ck_system_dataset_view_settings_article_variant
        CHECK (article_variant IN ('standard', 'image_first')),
    CONSTRAINT ck_system_dataset_view_settings_details_position
        CHECK (details_position IN (
            'between_title_and_description',
            'after_description'
        )),
    CONSTRAINT uq_system_dataset_view_settings_presentation
        UNIQUE (table_uid, presentation)
);

CREATE INDEX IF NOT EXISTS idx_system_dataset_view_settings_table_uid
    ON public.system_dataset_view_settings (table_uid);

COMMENT ON TABLE public.system_dataset_view_settings IS
    'Versioned per-dataset presentation settings. Only server-allowlisted presentation names and values are accepted.';
COMMENT ON COLUMN public.system_dataset_view_settings.article_variant IS
    'Article presentation: standard or image_first.';
COMMENT ON COLUMN public.system_dataset_view_settings.details_position IS
    'Article details placement: between_title_and_description or after_description.';

CREATE OR REPLACE FUNCTION public.set_system_dataset_view_settings_updated_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'update_system_dataset_view_settings_timestamp'
          AND tgrelid = 'public.system_dataset_view_settings'::regclass
    ) THEN
        CREATE TRIGGER update_system_dataset_view_settings_timestamp
            BEFORE UPDATE ON public.system_dataset_view_settings
            FOR EACH ROW
            EXECUTE FUNCTION public.set_system_dataset_view_settings_updated_timestamp();
    END IF;
END $$;

INSERT INTO public.system_db_tables (
    table_name,
    description,
    cached_oid,
    folder_id,
    schema_name,
    fk_display_column,
    filterbar_visible_by_default,
    is_removable,
    display_name,
    sql_dump_policy
)
SELECT
    'system_dataset_view_settings',
    'Versioned per-dataset presentation settings',
    tables.oid::INTEGER,
    (
        SELECT metadata.folder_id
        FROM public.system_db_tables AS metadata
        WHERE metadata.table_name = 'system_db_tables'
          AND COALESCE(NULLIF(metadata.schema_name, ''), 'public') = 'public'
        LIMIT 1
    ),
    'public',
    'presentation',
    FALSE,
    FALSE,
    'Dataset View Settings',
    'all'
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE tables.relname = 'system_dataset_view_settings'
  AND NOT EXISTS (
      SELECT 1
      FROM public.system_db_tables AS existing
      WHERE existing.table_name = 'system_dataset_view_settings'
        AND COALESCE(NULLIF(existing.schema_name, ''), 'public') = 'public'
  );

UPDATE public.system_db_tables AS target
SET description = 'Versioned per-dataset presentation settings',
    cached_oid = tables.oid::INTEGER,
    schema_name = 'public',
    fk_display_column = 'presentation',
    filterbar_visible_by_default = FALSE,
    is_removable = FALSE,
    display_name = 'Dataset View Settings',
    sql_dump_policy = 'all',
    updated = now()
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE target.table_name = 'system_dataset_view_settings'
  AND COALESCE(NULLIF(target.schema_name, ''), 'public') = 'public'
  AND tables.relname = 'system_dataset_view_settings';

DO $$
DECLARE
    registered_table_uid INTEGER;
BEGIN
    SELECT table_uid
    INTO registered_table_uid
    FROM public.system_db_tables
    WHERE table_name = 'system_dataset_view_settings'
      AND COALESCE(NULLIF(schema_name, ''), 'public') = 'public'
    LIMIT 1;

    IF registered_table_uid IS NOT NULL THEN
        INSERT INTO public.system_column_details (
            table_uid,
            column_name,
            data_type,
            co_number,
            editable_in_ui,
            created,
            updated
        )
        SELECT
            registered_table_uid,
            columns.column_name,
            columns.data_type,
            columns.ordinal_position,
            columns.column_name IN (
                'table_uid',
                'article_variant',
                'details_position'
            ),
            now(),
            now()
        FROM information_schema.columns AS columns
        WHERE columns.table_schema = 'public'
          AND columns.table_name = 'system_dataset_view_settings'
          AND NOT EXISTS (
              SELECT 1
              FROM public.system_column_details AS existing
              WHERE existing.table_uid = registered_table_uid
                AND existing.column_name = columns.column_name
          )
        ORDER BY columns.ordinal_position;
    END IF;
END $$;

DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'readeronly') THEN
        GRANT SELECT ON TABLE public.system_dataset_view_settings TO readeronly;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'guest_user') THEN
        GRANT SELECT ON TABLE public.system_dataset_view_settings TO guest_user;
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'basic_user') THEN
        GRANT SELECT, INSERT, UPDATE, DELETE
            ON TABLE public.system_dataset_view_settings TO basic_user;
        GRANT USAGE, SELECT
            ON SEQUENCE public.system_dataset_view_settings_id_seq TO basic_user;
    END IF;
END $$;

