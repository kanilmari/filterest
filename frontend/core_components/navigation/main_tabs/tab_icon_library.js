/**
 * Look up an icon path by key name.
 * Returns the default table icon if the key is null/undefined/unknown.
 *
 * @param {string|null|undefined} key - Icon key from system_db_tables.icon_key
 * @returns {string} SVG path `d` attribute string
 */
export function getTabIconPath(key) {
    if (!key) return ICON_PATHS.table;
    return ICON_PATHS[key] || ICON_PATHS.table;
}

/**
 * Get a sorted list of all available icon key names.
 * Useful for building an icon picker in admin UI.
 *
 * @returns {string[]}
 */
export function getAvailableIconKeys() {
    return Object.keys(ICON_PATHS).sort();
}

