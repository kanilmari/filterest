-- 20260819000002_add_dataset_media.sql
-- Adds one canonical registry for dataset-level cover and content-background
-- images. Row assets remain in each dataset's shared asset table; these two
-- presentation images are deliberately stored separately.
-- VERSION_DB: 9.2.0
-- VERSION_DB_OWNER: 20260819000003_record_dataset_media_db_release.sql

CREATE TABLE IF NOT EXISTS public.system_dataset_media (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_uid     INTEGER     NOT NULL
        REFERENCES public.system_db_tables(table_uid) ON DELETE CASCADE,
    media_role    TEXT        NOT NULL,
    storage_key   TEXT        NOT NULL,
    original_name TEXT        NOT NULL,
    mime_type     TEXT        NOT NULL,
    alt_text      JSONB       NOT NULL DEFAULT '{}'::jsonb,
    focal_x       NUMERIC(5, 4) NOT NULL DEFAULT 0.5000,
    focal_y       NUMERIC(5, 4) NOT NULL DEFAULT 0.5000,
    variants      JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_system_dataset_media_role
        CHECK (media_role IN ('cover', 'background')),
    CONSTRAINT ck_system_dataset_media_storage_key
        CHECK (btrim(storage_key) <> '' AND storage_key !~ '(^|/)\.\.(/|$)'),
    CONSTRAINT ck_system_dataset_media_focal_x
        CHECK (focal_x BETWEEN 0 AND 1),
    CONSTRAINT ck_system_dataset_media_focal_y
        CHECK (focal_y BETWEEN 0 AND 1),
    CONSTRAINT uq_system_dataset_media_role
        UNIQUE (table_uid, media_role)
);

CREATE INDEX IF NOT EXISTS idx_system_dataset_media_table_uid
    ON public.system_dataset_media (table_uid);

COMMENT ON TABLE public.system_dataset_media IS
    'One dataset-level cover or content-background image per role. storage_key is relative to the configured storage root.';
COMMENT ON COLUMN public.system_dataset_media.alt_text IS
    'BCP 47 language-code to accessible alternative-text mapping.';
COMMENT ON COLUMN public.system_dataset_media.variants IS
    'Logical generated image variants; keys are variant names and values are storage-root-relative paths.';

CREATE OR REPLACE FUNCTION public.set_system_dataset_media_updated_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'update_system_dataset_media_timestamp'
          AND tgrelid = 'public.system_dataset_media'::regclass
    ) THEN
        CREATE TRIGGER update_system_dataset_media_timestamp
            BEFORE UPDATE ON public.system_dataset_media
            FOR EACH ROW
            EXECUTE FUNCTION public.set_system_dataset_media_updated_timestamp();
    END IF;
END $$;

INSERT INTO public.system_db_tables (
    table_name,
    description,
    cached_oid,
    folder_id,
    schema_name,
    fk_display_column,
    filterbar_visible_by_default,
    is_removable,
    display_name,
    sql_dump_policy
)
SELECT
    'system_dataset_media',
    'Dataset-level cover and content-background image registry',
    tables.oid::INTEGER,
    (
        SELECT metadata.folder_id
        FROM public.system_db_tables AS metadata
        WHERE metadata.table_name = 'system_db_tables'
          AND COALESCE(NULLIF(metadata.schema_name, ''), 'public') = 'public'
        LIMIT 1
    ),
    'public',
    'original_name',
    FALSE,
    FALSE,
    'Dataset Media',
    'all'
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE tables.relname = 'system_dataset_media'
  AND NOT EXISTS (
      SELECT 1
      FROM public.system_db_tables AS existing
      WHERE existing.table_name = 'system_dataset_media'
        AND COALESCE(NULLIF(existing.schema_name, ''), 'public') = 'public'
  );

UPDATE public.system_db_tables AS target
SET description = 'Dataset-level cover and content-background image registry',
    cached_oid = tables.oid::INTEGER,
    schema_name = 'public',
    fk_display_column = 'original_name',
    filterbar_visible_by_default = FALSE,
    is_removable = FALSE,
    display_name = 'Dataset Media',
    sql_dump_policy = 'all',
    updated = now()
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE target.table_name = 'system_dataset_media'
  AND COALESCE(NULLIF(target.schema_name, ''), 'public') = 'public'
  AND tables.relname = 'system_dataset_media';

DO $$
DECLARE
    registered_table_uid INTEGER;
BEGIN
    SELECT table_uid
    INTO registered_table_uid
    FROM public.system_db_tables
    WHERE table_name = 'system_dataset_media'
      AND COALESCE(NULLIF(schema_name, ''), 'public') = 'public'
    LIMIT 1;

    IF registered_table_uid IS NOT NULL THEN
        INSERT INTO public.system_column_details (
            table_uid,
            column_name,
            data_type,
            co_number,
            editable_in_ui,
            created,
            updated
        )
        SELECT
            registered_table_uid,
            columns.column_name,
            columns.data_type,
            columns.ordinal_position,
            FALSE,
            now(),
            now()
        FROM information_schema.columns AS columns
        WHERE columns.table_schema = 'public'
          AND columns.table_name = 'system_dataset_media'
          AND NOT EXISTS (
              SELECT 1
              FROM public.system_column_details AS existing
              WHERE existing.table_uid = registered_table_uid
                AND existing.column_name = columns.column_name
          )
        ORDER BY columns.ordinal_position;
    END IF;
END $$;

WITH authored_keys(lang_key, fi, en, ch, yue, creation_spec) AS (
    VALUES
        (
            'system_dataset_media',
            'Tietojoukkojen kuvat',
            'Dataset Media',
            '数据集媒体',
            '資料集媒體',
            'Static database-tree label for dataset-level cover and background image metadata.'
        )
)
INSERT INTO public.system_lang_keys (lang_key, fi, en, ch, yue, creation_spec)
SELECT authored.lang_key, authored.fi, authored.en, authored.ch, authored.yue, authored.creation_spec
FROM authored_keys AS authored
ON CONFLICT (lang_key) DO UPDATE
SET fi = EXCLUDED.fi,
    en = EXCLUDED.en,
    ch = EXCLUDED.ch,
    yue = EXCLUDED.yue,
    creation_spec = EXCLUDED.creation_spec,
    updated = now();

WITH authored_translations(lang_key, language_code, translation, review_status) AS (
    VALUES
        ('system_dataset_media', 'en', 'Dataset Media', 'approved'),
        ('system_dataset_media', 'fi', 'Tietojoukkojen kuvat', 'approved'),
        ('system_dataset_media', 'zh-CN', '数据集媒体', 'needs_review'),
        ('system_dataset_media', 'zh-TW', '資料集媒體', 'needs_review'),
        ('system_dataset_media', 'zh-HK', '資料集媒體', 'needs_review')
), resolved AS (
    SELECT keys.id AS lang_key_id,
           authored.language_code,
           authored.translation,
           authored.review_status
    FROM authored_translations AS authored
    JOIN public.system_lang_keys AS keys ON keys.lang_key = authored.lang_key
)
INSERT INTO public.system_lang_key_translations (
    lang_key_id,
    language_code,
    translation,
    source_kind,
    review_status
)
SELECT resolved.lang_key_id,
       resolved.language_code,
       resolved.translation,
       'manual',
       resolved.review_status
FROM resolved
ON CONFLICT (lang_key_id, language_code) DO UPDATE
SET translation = EXCLUDED.translation,
    source_kind = EXCLUDED.source_kind,
    review_status = EXCLUDED.review_status,
    updated = now();
