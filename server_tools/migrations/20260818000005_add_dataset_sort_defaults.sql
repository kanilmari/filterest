-- 20260818000005_add_dataset_sort_defaults.sql
-- Adds persistent per-dataset sorting defaults for the current administrator
-- and for every site visitor. The setting is additive and does not change
-- existing query URLs or rows.
-- VERSION_DB: 9.1.0

CREATE TABLE IF NOT EXISTS public.system_dataset_sort_defaults (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_uid      INTEGER     NOT NULL
        REFERENCES public.system_db_tables(table_uid) ON DELETE CASCADE,
    user_id        INTEGER
        REFERENCES public.system_users(id) ON DELETE CASCADE,
    sort_column    TEXT        NOT NULL,
    sort_direction TEXT        NOT NULL,
    created        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_system_dataset_sort_defaults_column
        CHECK (btrim(sort_column) <> ''),
    CONSTRAINT ck_system_dataset_sort_defaults_direction
        CHECK (sort_direction IN ('ASC', 'DESC')),
    CONSTRAINT uq_system_dataset_sort_defaults_scope
        UNIQUE NULLS NOT DISTINCT (table_uid, user_id)
);

CREATE INDEX IF NOT EXISTS idx_system_dataset_sort_defaults_user
    ON public.system_dataset_sort_defaults (user_id, table_uid)
    WHERE user_id IS NOT NULL;

COMMENT ON TABLE public.system_dataset_sort_defaults IS
    'Persistent dataset sorting defaults. NULL user_id is the site-wide default; a user_id row overrides it for that administrator.';
COMMENT ON COLUMN public.system_dataset_sort_defaults.sort_column IS
    'A validated physical dataset column or the __images_first / __search_relevance virtual sort key.';

WITH desired_functions (
    name,
    package,
    specific_table_related,
    url_route_endpoint
) AS (
    VALUES
        ('system_table_tools.GetDatasetSortDefaultHandler', 'system_table_tools', FALSE, '/api/dataset-sort-default'),
        ('system_table_tools.SaveDatasetSortDefaultHandler', 'system_table_tools', FALSE, '/api/admin/dataset-sort-default')
), missing_functions AS (
    SELECT desired.*, ROW_NUMBER() OVER (ORDER BY desired.name) AS id_offset
    FROM desired_functions AS desired
    WHERE NOT EXISTS (
        SELECT 1
        FROM public.system_functions AS existing
        WHERE existing.name = desired.name
    )
), current_id AS (
    SELECT COALESCE(MAX(id), 0)::BIGINT AS max_id
    FROM public.system_functions
)
INSERT INTO public.system_functions (
    id,
    name,
    disabled,
    created,
    updated,
    package,
    specific_table_related,
    creation_spec,
    rate_limit_amount,
    rate_limit_minutes,
    url_route_endpoint,
    ui_only
)
SELECT
    current_id.max_id + missing.id_offset,
    missing.name,
    FALSE,
    now(),
    now(),
    missing.package,
    missing.specific_table_related,
    'Filterest DB 9.1.0 dataset sorting defaults',
    300,
    20,
    missing.url_route_endpoint,
    FALSE
FROM missing_functions AS missing
CROSS JOIN current_id;

WITH desired_functions (
    name,
    package,
    specific_table_related,
    url_route_endpoint
) AS (
    VALUES
        ('system_table_tools.GetDatasetSortDefaultHandler', 'system_table_tools', FALSE, '/api/dataset-sort-default'),
        ('system_table_tools.SaveDatasetSortDefaultHandler', 'system_table_tools', FALSE, '/api/admin/dataset-sort-default')
)
UPDATE public.system_functions AS target
SET disabled = FALSE,
    updated = now(),
    package = desired.package,
    specific_table_related = desired.specific_table_related,
    creation_spec = 'Filterest DB 9.1.0 dataset sorting defaults',
    rate_limit_amount = 300,
    rate_limit_minutes = 20,
    url_route_endpoint = desired.url_route_endpoint,
    ui_only = FALSE
FROM desired_functions AS desired
WHERE target.name = desired.name;

INSERT INTO public.system_group_table_func_rights (
    user_group_id,
    function_id,
    target_schema_name,
    creation_spec,
    target_table_uid
)
SELECT
    groups.id,
    functions.id,
    'public',
    'Filterest DB 9.1.0 dataset sorting defaults',
    NULL
FROM public.system_user_groups AS groups
JOIN public.system_functions AS functions
  ON functions.name = 'system_table_tools.SaveDatasetSortDefaultHandler'
WHERE groups.name = 'admins'
  AND NOT EXISTS (
      SELECT 1
      FROM public.system_group_table_func_rights AS existing
      WHERE existing.user_group_id = groups.id
        AND existing.function_id = functions.id
        AND existing.target_table_uid IS NULL
  );

CREATE OR REPLACE FUNCTION public.set_system_dataset_sort_defaults_updated_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_trigger
        WHERE tgname = 'update_system_dataset_sort_defaults_timestamp'
          AND tgrelid = 'public.system_dataset_sort_defaults'::regclass
    ) THEN
        CREATE TRIGGER update_system_dataset_sort_defaults_timestamp
            BEFORE UPDATE ON public.system_dataset_sort_defaults
            FOR EACH ROW
            EXECUTE FUNCTION public.set_system_dataset_sort_defaults_updated_timestamp();
    END IF;
END $$;

INSERT INTO public.system_db_tables (
    table_name,
    description,
    cached_oid,
    folder_id,
    schema_name,
    fk_display_column,
    filterbar_visible_by_default,
    is_removable,
    display_name,
    sql_dump_policy
)
SELECT
    'system_dataset_sort_defaults',
    'Per-dataset site-wide and administrator-specific default sorting',
    tables.oid::INTEGER,
    (
        SELECT metadata.folder_id
        FROM public.system_db_tables AS metadata
        WHERE metadata.table_name = 'system_db_tables'
          AND COALESCE(NULLIF(metadata.schema_name, ''), 'public') = 'public'
        LIMIT 1
    ),
    'public',
    'sort_column',
    FALSE,
    FALSE,
    'Dataset Sort Defaults',
    'schema_only'
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE tables.relname = 'system_dataset_sort_defaults'
  AND NOT EXISTS (
      SELECT 1
      FROM public.system_db_tables AS existing
      WHERE existing.table_name = 'system_dataset_sort_defaults'
        AND COALESCE(NULLIF(existing.schema_name, ''), 'public') = 'public'
  );

UPDATE public.system_db_tables AS target
SET description = 'Per-dataset site-wide and administrator-specific default sorting',
    cached_oid = tables.oid::INTEGER,
    schema_name = 'public',
    fk_display_column = 'sort_column',
    filterbar_visible_by_default = FALSE,
    is_removable = FALSE,
    display_name = 'Dataset Sort Defaults',
    sql_dump_policy = 'schema_only',
    updated = now()
FROM pg_class AS tables
JOIN pg_namespace AS schemas
  ON schemas.oid = tables.relnamespace
 AND schemas.nspname = 'public'
WHERE target.table_name = 'system_dataset_sort_defaults'
  AND COALESCE(NULLIF(target.schema_name, ''), 'public') = 'public'
  AND tables.relname = 'system_dataset_sort_defaults';

DO $$
DECLARE
    registered_table_uid INTEGER;
BEGIN
    SELECT table_uid
    INTO registered_table_uid
    FROM public.system_db_tables
    WHERE table_name = 'system_dataset_sort_defaults'
      AND COALESCE(NULLIF(schema_name, ''), 'public') = 'public'
    LIMIT 1;

    IF registered_table_uid IS NOT NULL THEN
        INSERT INTO public.system_column_details (
            table_uid,
            column_name,
            data_type,
            co_number,
            editable_in_ui,
            created,
            updated
        )
        SELECT
            registered_table_uid,
            columns.column_name,
            columns.data_type,
            columns.ordinal_position,
            FALSE,
            now(),
            now()
        FROM information_schema.columns AS columns
        WHERE columns.table_schema = 'public'
          AND columns.table_name = 'system_dataset_sort_defaults'
          AND NOT EXISTS (
              SELECT 1
              FROM public.system_column_details AS existing
              WHERE existing.table_uid = registered_table_uid
                AND existing.column_name = columns.column_name
          )
        ORDER BY columns.ordinal_position;
    END IF;
END $$;

